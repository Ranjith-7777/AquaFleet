"""
routes/vessels.py
-----------------
CRUD REST API for the `research_vessel` table.

All five endpoints live on one Flask Blueprint so that app.py stays small:

    GET    /api/vessels             list every vessel
    GET    /api/vessels/<id>        fetch one vessel
    POST   /api/vessels             create a vessel
    PUT    /api/vessels/<id>        replace a vessel
    DELETE /api/vessels/<id>        delete a vessel

Rules followed throughout this module:
  * every SQL statement is parameterized with %s - never string formatting
  * SELECT statements use a dictionary cursor so rows come back as dicts
  * write statements commit on success and roll back on failure
  * cursors and connections are always released in a finally block
  * MySQL driver errors are logged in full but never sent to the client
"""

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

# url_prefix means every route below is automatically under /api/vessels
vessels_bp = Blueprint("vessels", __name__, url_prefix="/api/vessels")


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "vessel_name": 100,
    "vessel_type": 50,
    "home_port": 100,
}

# Every field a client is allowed to send. vessel_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | {"capacity"}

# Columns selected by every read, in a fixed order.
VESSEL_COLUMNS = "vessel_id, vessel_name, vessel_type, capacity, home_port"

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response.

    The client only ever sees a generic message: raw SQL, connection settings
    and driver internals stay in the server log.
    """
    current_app.logger.error("Vessel %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def validate_vessel_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` is a dict ready for the SQL parameters, with the text
    fields trimmed. `errors` maps a field name to its problem. When `errors`
    is non-empty the caller must reject the request with HTTP 400.

    All problems are collected in one pass so the client can fix everything
    at once instead of discovering them one request at a time.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a string. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Text fields: required, must be a non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- capacity: a positive integer. ---
    capacity = payload.get("capacity")
    capacity_error = "capacity must be an integer greater than 0"

    if capacity is None:
        errors["capacity"] = "capacity is required"
    elif isinstance(capacity, bool):
        # bool is a subclass of int in Python, so True would otherwise pass
        # the isinstance check below and be stored as capacity = 1.
        errors["capacity"] = capacity_error
    elif not isinstance(capacity, int):
        errors["capacity"] = capacity_error
    elif capacity <= 0:
        errors["capacity"] = capacity_error
    else:
        cleaned["capacity"] = capacity

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_vessel(cursor, vessel_id):
    """Return one vessel as a dict, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {VESSEL_COLUMNS} FROM research_vessel WHERE vessel_id = %s",
        (vessel_id,)
    )
    return cursor.fetchone()


def not_found_response():
    """Build the standard HTTP 404 body for a missing vessel."""
    return jsonify({
        "success": False,
        "message": "Research vessel not found"
    }), 404


def duplicate_name_response():
    """Build the standard HTTP 409 body for a UNIQUE(vessel_name) violation."""
    return jsonify({
        "success": False,
        "message": "A research vessel with this name already exists"
    }), 409


# ============================================================================
# ENDPOINT 1 - list all vessels
# ============================================================================

@vessels_bp.route("", methods=["GET"])
def list_vessels():
    """GET /api/vessels - every vessel, ordered by vessel_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {VESSEL_COLUMNS} FROM research_vessel ORDER BY vessel_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        return jsonify({
            "success": True,
            "count": len(rows),
            "data": rows
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one vessel
# ============================================================================

@vessels_bp.route("/<int:vessel_id>", methods=["GET"])
def get_vessel(vessel_id):
    """GET /api/vessels/<id> - one vessel, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        vessel = fetch_vessel(cursor, vessel_id)

        if vessel is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": vessel
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a vessel
# ============================================================================

@vessels_bp.route("", methods=["POST"])
def create_vessel():
    """POST /api/vessels - validate, insert, return the new row."""
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_vessel_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        cursor.execute(
            """
            INSERT INTO research_vessel (vessel_name, vessel_type, capacity, home_port)
            VALUES (%s, %s, %s, %s)
            """,
            (
                cleaned["vessel_name"],
                cleaned["vessel_type"],
                cleaned["capacity"],
                cleaned["home_port"],
            )
        )
        connection.commit()

        # MySQL generated the primary key for us.
        new_id = cursor.lastrowid

        return jsonify({
            "success": True,
            "message": "Research vessel created successfully",
            "data": {
                "vessel_id": new_id,
                "vessel_name": cleaned["vessel_name"],
                "vessel_type": cleaned["vessel_type"],
                "capacity": cleaned["capacity"],
                "home_port": cleaned["home_port"],
            }
        }), 201

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # Letting MySQL detect the duplicate - rather than doing a SELECT
        # first - is what makes this correct when two requests race.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace a vessel
# ============================================================================

@vessels_bp.route("/<int:vessel_id>", methods=["PUT"])
def update_vessel(vessel_id):
    """PUT /api/vessels/<id> - full replacement of the four editable columns."""
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so all four fields are required, exactly
    # as they are for POST.
    cleaned, errors = validate_vessel_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_vessel(cursor, vessel_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE research_vessel
               SET vessel_name = %s,
                   vessel_type = %s,
                   capacity    = %s,
                   home_port   = %s
             WHERE vessel_id = %s
            """,
            (
                cleaned["vessel_name"],
                cleaned["vessel_type"],
                cleaned["capacity"],
                cleaned["home_port"],
                vessel_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Research vessel updated successfully",
            "data": {
                "vessel_id": vessel_id,
                "vessel_name": cleaned["vessel_name"],
                "vessel_type": cleaned["vessel_type"],
                "capacity": cleaned["capacity"],
                "home_port": cleaned["home_port"],
            }
        }), 200

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # Renaming a vessel to a name another vessel already uses.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - delete a vessel
# ============================================================================

@vessels_bp.route("/<int:vessel_id>", methods=["DELETE"])
def delete_vessel(vessel_id):
    """DELETE /api/vessels/<id> - remove a vessel that no expedition uses."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        if fetch_vessel(cursor, vessel_id) is None:
            return not_found_response()

        cursor.execute(
            "DELETE FROM research_vessel WHERE vessel_id = %s",
            (vessel_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Research vessel deleted successfully"
        }), 200

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # expedition.vessel_id uses ON DELETE RESTRICT, so MySQL refuses the
        # delete itself. We report that instead of removing the expeditions.
        if err.errno == errorcode.ER_ROW_IS_REFERENCED_2:
            return jsonify({
                "success": False,
                "message": "Research vessel cannot be deleted because it is "
                           "assigned to one or more expeditions"
            }), 409

        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
