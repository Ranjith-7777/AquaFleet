"""
routes/marine_zones.py
----------------------
CRUD REST API for the `marine_zone` table.

    GET    /api/marine-zones             list every zone
    GET    /api/marine-zones/<id>        fetch one zone
    POST   /api/marine-zones             create a zone
    PUT    /api/marine-zones/<id>        replace a zone
    DELETE /api/marine-zones/<id>        delete a zone

This module follows the same conventions as routes/vessels.py: parameterized
SQL, dictionary cursors for reads, commit/rollback around writes, cleanup in
finally blocks, full error logging server-side and a generic message to the
client.

The one thing that differs from vessels.py is the depth columns. min_depth and
max_depth are DECIMAL(8,2), so the driver hands them back as decimal.Decimal,
which jsonify() cannot serialize. Every value is therefore validated through
Decimal (never binary float arithmetic) and converted back to a plain JSON
number on the way out.
"""

import math
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

marine_zones_bp = Blueprint(
    "marine_zones",
    __name__,
    url_prefix="/api/marine-zones"
)


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "zone_name": 100,
    "region": 100,
}

# The DECIMAL(8,2) depth columns.
DEPTH_FIELDS = ("min_depth", "max_depth")

# Must match chk_zone_risk_level in schema.sql exactly, including the casing.
RISK_LEVELS = ("Low", "Moderate", "High", "Critical")

# Every field a client may send. zone_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | set(DEPTH_FIELDS) | {"risk_level"}

# DECIMAL(8,2) means 8 total digits with 2 after the point, so the largest
# value the column can hold is 999999.99.
MAX_DEPTH_VALUE = Decimal("999999.99")
DECIMAL_PLACES = 2

# Columns selected by every read, in a fixed order.
ZONE_COLUMNS = "zone_id, zone_name, region, min_depth, max_depth, risk_level"

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Marine zone %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every depth read back from
    MySQL passes through here. float() is safe at this point because the value
    has already been constrained to at most 8 digits with 2 decimal places,
    which a double represents exactly enough for display.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def serialize_zone(row):
    """Convert one database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "zone_id": row["zone_id"],
        "zone_name": row["zone_name"],
        "region": row["region"],
        "min_depth": decimal_to_number(row["min_depth"]),
        "max_depth": decimal_to_number(row["max_depth"]),
        "risk_level": row["risk_level"],
    }


def parse_depth(field, value, errors):
    """Validate one depth field and return it as a Decimal, or None.

    Records its own problem in `errors` and returns None when the value is
    unusable, so the caller can keep collecting the remaining errors.
    """
    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise be accepted
    # and stored as a depth of 1.
    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    # Rejects strings such as "50" as well as lists, dicts and null.
    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        # Decimal(value) on a float would introduce binary rounding noise and
        # make the decimal-place check meaningless.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    # exponent -3 means three digits after the point, and so on.
    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_DEPTH_VALUE:
        errors[field] = f"{field} must not exceed {MAX_DEPTH_VALUE}"
        return None

    return parsed


def validate_zone_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` holds trimmed text and Decimal depths ready to be used as
    SQL parameters. When `errors` is non-empty the caller must reject the
    request with HTTP 400. All problems are collected in one pass.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- risk_level: trimmed, then an exact match against the CHECK list. ---
    risk_level = payload.get("risk_level")
    allowed_display = ", ".join(RISK_LEVELS)

    if risk_level is None:
        errors["risk_level"] = "risk_level is required"
    elif not isinstance(risk_level, str):
        errors["risk_level"] = "risk_level must be a string"
    else:
        trimmed_risk = risk_level.strip()
        if not trimmed_risk:
            errors["risk_level"] = "risk_level must not be empty"
        elif trimmed_risk not in RISK_LEVELS:
            # Case is significant: 'low' is rejected rather than corrected,
            # so a client typo never turns into a silently different value.
            errors["risk_level"] = f"risk_level must be one of: {allowed_display}"
        else:
            cleaned["risk_level"] = trimmed_risk

    # --- Depths: numeric, finite, in range, at most two decimal places. ---
    min_depth = parse_depth("min_depth", payload.get("min_depth"), errors)
    max_depth = parse_depth("max_depth", payload.get("max_depth"), errors)

    if min_depth is not None:
        if min_depth < 0:
            errors["min_depth"] = "min_depth must be greater than or equal to 0"
        else:
            cleaned["min_depth"] = min_depth

    if max_depth is not None:
        # Only comparable when min_depth itself was valid.
        if min_depth is not None and max_depth < min_depth:
            errors["max_depth"] = "max_depth must be greater than or equal to min_depth"
        else:
            cleaned["max_depth"] = max_depth

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_zone(cursor, zone_id):
    """Return one zone row, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {ZONE_COLUMNS} FROM marine_zone WHERE zone_id = %s",
        (zone_id,)
    )
    return cursor.fetchone()


def not_found_response():
    """Build the standard HTTP 404 body for a missing zone."""
    return jsonify({
        "success": False,
        "message": "Marine zone not found"
    }), 404


def duplicate_name_response():
    """Build the standard HTTP 409 body for a UNIQUE(zone_name) violation."""
    return jsonify({
        "success": False,
        "message": "A marine zone with this name already exists"
    }), 409


# ============================================================================
# ENDPOINT 1 - list all zones
# ============================================================================

@marine_zones_bp.route("", methods=["GET"])
def list_marine_zones():
    """GET /api/marine-zones - every zone, ordered by zone_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {ZONE_COLUMNS} FROM marine_zone ORDER BY zone_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        zones = [serialize_zone(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(zones),
            "data": zones
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one zone
# ============================================================================

@marine_zones_bp.route("/<int:zone_id>", methods=["GET"])
def get_marine_zone(zone_id):
    """GET /api/marine-zones/<id> - one zone, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_zone(cursor, zone_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_zone(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a zone
# ============================================================================

@marine_zones_bp.route("", methods=["POST"])
def create_marine_zone():
    """POST /api/marine-zones - validate, insert, return the new row."""
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_zone_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        # The Decimal objects are passed straight through as parameters; the
        # driver renders them without any float round-trip.
        cursor.execute(
            """
            INSERT INTO marine_zone (zone_name, region, min_depth, max_depth, risk_level)
            VALUES (%s, %s, %s, %s, %s)
            """,
            (
                cleaned["zone_name"],
                cleaned["region"],
                cleaned["min_depth"],
                cleaned["max_depth"],
                cleaned["risk_level"],
            )
        )
        connection.commit()

        new_id = cursor.lastrowid

        return jsonify({
            "success": True,
            "message": "Marine zone created successfully",
            "data": {
                "zone_id": new_id,
                "zone_name": cleaned["zone_name"],
                "region": cleaned["region"],
                "min_depth": decimal_to_number(cleaned["min_depth"]),
                "max_depth": decimal_to_number(cleaned["max_depth"]),
                "risk_level": cleaned["risk_level"],
            }
        }), 201

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # Letting MySQL detect the duplicate - rather than doing a SELECT
        # first - is what makes this correct when two requests race.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace a zone
# ============================================================================

@marine_zones_bp.route("/<int:zone_id>", methods=["PUT"])
def update_marine_zone(zone_id):
    """PUT /api/marine-zones/<id> - full replacement of the five columns."""
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so all five fields are required, exactly
    # as they are for POST.
    cleaned, errors = validate_zone_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_zone(cursor, zone_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE marine_zone
               SET zone_name  = %s,
                   region     = %s,
                   min_depth  = %s,
                   max_depth  = %s,
                   risk_level = %s
             WHERE zone_id = %s
            """,
            (
                cleaned["zone_name"],
                cleaned["region"],
                cleaned["min_depth"],
                cleaned["max_depth"],
                cleaned["risk_level"],
                zone_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Marine zone updated successfully",
            "data": {
                "zone_id": zone_id,
                "zone_name": cleaned["zone_name"],
                "region": cleaned["region"],
                "min_depth": decimal_to_number(cleaned["min_depth"]),
                "max_depth": decimal_to_number(cleaned["max_depth"]),
                "risk_level": cleaned["risk_level"],
            }
        }), 200

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # Renaming a zone to a name another zone already uses.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - delete a zone
# ============================================================================

@marine_zones_bp.route("/<int:zone_id>", methods=["DELETE"])
def delete_marine_zone(zone_id):
    """DELETE /api/marine-zones/<id> - remove a zone no mission uses."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        if fetch_zone(cursor, zone_id) is None:
            return not_found_response()

        cursor.execute(
            "DELETE FROM marine_zone WHERE zone_id = %s",
            (zone_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Marine zone deleted successfully"
        }), 200

    except MySQLError as err:
        if connection is not None:
            connection.rollback()

        # mission.zone_id uses ON DELETE RESTRICT, so MySQL refuses the delete
        # itself. We report that instead of touching the dependent missions.
        if err.errno == errorcode.ER_ROW_IS_REFERENCED_2:
            return jsonify({
                "success": False,
                "message": "Marine zone cannot be deleted because it is "
                           "assigned to one or more missions"
            }), 409

        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
