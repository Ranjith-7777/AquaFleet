# ENDPOINT 4 - replace an expedition
# ============================================================================

@expeditions_bp.route("/<int:expedition_id>", methods=["PUT"])
def update_expedition(expedition_id):
    """PUT /api/expeditions/<id> - full replacement of the seven columns.

    Beyond the usual validation, a date range that would leave existing
    missions outside it is refused with 409. Missions are never moved or
    deleted to make a new range fit.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_expedition_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it underneath the rewrite.
        cursor.execute(
            "SELECT expedition_id FROM expedition WHERE expedition_id = %s FOR UPDATE",
            (expedition_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        vessel = fetch_vessel_details(cursor, cleaned["vessel_id"])
        if vessel is None:
            connection.rollback()
            return validation_response({
                "vessel_id": "vessel_id does not reference an existing research vessel"
            })

        vessel_name, home_port = vessel

        # Refuse to strand existing missions outside the proposed window.
        outside = count_missions_outside_range(
            cursor, expedition_id, cleaned["start_date"], cleaned["end_date"]
        )
        if outside > 0:
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Expedition dates cannot be updated because existing "
                           "missions would fall outside the new date range"
            }), 409

        cursor.execute(
            """
            UPDATE expedition
               SET vessel_id  = %s,
                   title      = %s,
                   start_date = %s,
                   end_date   = %s,
                   objective  = %s,
                   status     = %s,
                   budget     = %s
             WHERE expedition_id = %s
            """,
            (
                cleaned["vessel_id"],
                cleaned["title"],
                cleaned["start_date"],
                cleaned["end_date"],
                cleaned["objective"],
                cleaned["status"],
                cleaned["budget"],
                expedition_id,
            )
        )

        mission_count = count_missions(cursor, expedition_id)
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Expedition updated successfully",
            "data": build_expedition_payload(
                expedition_id, cleaned, vessel_name, home_port, mission_count
            )
        }), 200

    except MySQLError as err:
        safe_rollback(connection)

        if err.errno == errorcode.ER_NO_REFERENCED_ROW_2:
            return parent_reference_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


