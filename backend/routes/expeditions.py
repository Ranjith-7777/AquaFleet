"""
routes/expeditions.py
---------------------
CRUD REST API for the `expedition` table.

    GET    /api/expeditions             list every expedition
    GET    /api/expeditions/<id>        fetch one expedition
    POST   /api/expeditions             create an expedition
    PUT    /api/expeditions/<id>        replace an expedition
    DELETE /api/expeditions/<id>        delete an expedition with no missions

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, commit/rollback around
writes, cleanup in finally blocks, full error logging server-side and a
generic message to the client.

THREE THINGS WORTH KNOWING
--------------------------
1. Responses are joined. Every expedition carries its vessel's name and home
   port plus a mission_count, all from ONE statement - the count comes from a
   scalar subquery rather than a follow-up query per expedition.

2. vessel_id is a foreign key, so it is checked for existence before the write
   to produce a useful field-level error, and MySQL error 1452 is caught as a
   concurrency-safe fallback in case the vessel disappears in between.

3. Deleting an expedition CASCADES to its missions and, through them, to six
   further tables plus sample_aliquot - the widest blast radius in the schema.
   Expedition 1 alone would destroy roughly 33 rows across 8 tables without
   MySQL raising anything. This API blocks the delete whenever any mission
   exists, and PUT refuses to narrow the date range around missions that would
   then fall outside it.

There is no duplicate handling: `expedition` has no UNIQUE constraint, so two
campaigns may legitimately share a title and MySQL error 1062 is unreachable.
"""

import math
from datetime import date, datetime
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

expeditions_bp = Blueprint("expeditions", __name__, url_prefix="/api/expeditions")


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

TITLE_MAX_LENGTH = 150

# MySQL TEXT holds 65,535 BYTES, not characters. A multi-byte objective can
# therefore overflow well before 65,535 Python characters.
OBJECTIVE_MAX_BYTES = 65535

# Must match chk_expedition_status in schema.sql exactly, including the casing.
EXPEDITION_STATUSES = ("Planned", "Active", "Completed", "Cancelled")

# budget is DECIMAL(14,2): 14 total digits, 2 of them after the point.
MAX_BUDGET_VALUE = Decimal("999999999999.99")
DECIMAL_PLACES = 2

DATE_FORMAT = "%Y-%m-%d"

# Every field a client may send. expedition_id is generated by MySQL.
ALLOWED_FIELDS = {
    "vessel_id", "title", "start_date", "end_date", "objective", "status", "budget"
}

# One statement covers the vessel join and the mission count, so listing N
# expeditions never becomes N + 1 queries.
EXPEDITION_SELECT = """
    SELECT e.expedition_id,
           e.vessel_id,
           rv.vessel_name,
           rv.home_port,
           e.title,
           e.start_date,
           e.end_date,
           e.objective,
           e.status,
           e.budget,
           (SELECT COUNT(*) FROM mission m
             WHERE m.expedition_id = e.expedition_id) AS mission_count
      FROM expedition e
      JOIN research_vessel rv ON rv.vessel_id = e.vessel_id
"""

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Expedition %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every budget read back from
    MySQL passes through here.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def date_to_iso(value):
    """Render a DATE as YYYY-MM-DD.

    The driver returns datetime.date, which Flask would otherwise serialize as
    an RFC 1123 string like "Mon, 03 Nov 2025 00:00:00 GMT".
    """
    if isinstance(value, date):
        return value.isoformat()
    return value


def serialize_expedition(row):
    """Convert one joined database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "expedition_id": row["expedition_id"],
        "vessel_id": row["vessel_id"],
        "vessel_name": row["vessel_name"],
        "home_port": row["home_port"],
        "title": row["title"],
        "start_date": date_to_iso(row["start_date"]),
        "end_date": date_to_iso(row["end_date"]),
        "objective": row["objective"],
        "status": row["status"],
        "budget": decimal_to_number(row["budget"]),
        "mission_count": int(row["mission_count"]),
    }


def parse_positive_integer(field, value, errors):
    """Validate a foreign-key id: a genuine JSON integer greater than zero."""
    message = f"{field} must be an integer greater than 0"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise pass as 1.
    if isinstance(value, bool):
        errors[field] = message
        return None

    # A genuine integer only: 2.0 arrives as a float and is rejected, as are
    # strings, lists and dicts.
    if not isinstance(value, int):
        errors[field] = message
        return None

    if value <= 0:
        errors[field] = message
        return None

    return value


def parse_date(field, value, errors):
    """Validate a DATE strictly and return a datetime.date, or None.

    Only the exact form YYYY-MM-DD is accepted. strptime alone would also
    swallow "2026-1-5", so the parsed result is formatted back and compared
    against what was submitted. strptime itself rejects compact forms,
    timestamps, zero dates and impossible calendar dates such as 2026-02-30.
    """
    if value is None:
        errors[field] = f"{field} is required"
        return None

    if not isinstance(value, str):
        errors[field] = f"{field} must be a string"
        return None

    trimmed = value.strip()
    if not trimmed:
        errors[field] = f"{field} must not be empty"
        return None

    try:
        parsed = datetime.strptime(trimmed, DATE_FORMAT).date()
    except ValueError:
        errors[field] = f"{field} must be a valid date in YYYY-MM-DD format"
        return None

    if parsed.strftime(DATE_FORMAT) != trimmed:
        errors[field] = f"{field} must be a valid date in YYYY-MM-DD format"
        return None

    # Future dates are explicitly allowed: expeditions are planned ahead.
    return parsed


def parse_budget(value, errors):
    """Validate budget and return it as a Decimal, or None."""
    field = "budget"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_BUDGET_VALUE:
        errors[field] = f"{field} must not exceed {MAX_BUDGET_VALUE}"
        return None

    # chk_expedition_budget allows zero, so this is >= rather than >.
    if parsed < 0:
        errors[field] = f"{field} must be greater than or equal to 0"
        return None

    return parsed


def validate_expedition_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    Only local rules are applied here. Whether vessel_id actually exists is
    settled later, inside the write transaction.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- vessel_id: a genuine positive integer. ---
    vessel_id = parse_positive_integer("vessel_id", payload.get("vessel_id"), errors)
    if vessel_id is not None:
        cleaned["vessel_id"] = vessel_id

    # --- title: required, non-blank string, length-limited. ---
    title = payload.get("title")
    if title is None:
        errors["title"] = "title is required"
    elif not isinstance(title, str):
        errors["title"] = "title must be a string"
    else:
        trimmed_title = title.strip()
        if not trimmed_title:
            errors["title"] = "title must not be empty"
        elif len(trimmed_title) > TITLE_MAX_LENGTH:
            errors["title"] = f"title must be at most {TITLE_MAX_LENGTH} characters"
        else:
            cleaned["title"] = trimmed_title

    # --- objective: TEXT, so the limit is bytes rather than characters. ---
    objective = payload.get("objective")
    if objective is None:
        errors["objective"] = "objective is required"
    elif not isinstance(objective, str):
        errors["objective"] = "objective must be a string"
    else:
        trimmed_objective = objective.strip()
        if not trimmed_objective:
            errors["objective"] = "objective must not be empty"
        elif len(trimmed_objective.encode("utf-8")) > OBJECTIVE_MAX_BYTES:
            # Measured in encoded bytes: a multi-byte objective overflows TEXT
            # long before it reaches 65,535 Python characters.
            errors["objective"] = (
                f"objective must be at most {OBJECTIVE_MAX_BYTES} bytes when "
                "encoded as UTF-8"
            )
        else:
            cleaned["objective"] = trimmed_objective

    # --- Dates: strict format, then ordering. ---
    start_date = parse_date("start_date", payload.get("start_date"), errors)
    end_date = parse_date("end_date", payload.get("end_date"), errors)

    if start_date is not None:
        cleaned["start_date"] = start_date

    if end_date is not None:
        # chk_expedition_dates allows equality, so a one-day expedition is fine.
        # Only comparable when start_date itself parsed.
        if start_date is not None and end_date < start_date:
            errors["end_date"] = "end_date must be greater than or equal to start_date"
        else:
            cleaned["end_date"] = end_date

    # --- status: exact match against the CHECK list. ---
    status = payload.get("status")
    if status is None:
        errors["status"] = "status is required"
    elif not isinstance(status, str):
        errors["status"] = "status must be a string"
    else:
        trimmed_status = status.strip()
        if not trimmed_status:
            errors["status"] = "status must not be empty"
        elif trimmed_status not in EXPEDITION_STATUSES:
            # Case is significant: 'planned' is rejected, never corrected.
            errors["status"] = (
                f"status must be one of: {', '.join(EXPEDITION_STATUSES)}"
            )
        else:
            cleaned["status"] = trimmed_status

    # --- budget: numeric, finite, >= 0, <= 999999999999.99, 2 decimals. ---
    budget = parse_budget(payload.get("budget"), errors)
    if budget is not None:
        cleaned["budget"] = budget

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def parent_reference_response():
    """Build the HTTP 400 body for a MySQL 1452 foreign-key failure.

    Reached only if the vessel is deleted between the existence check and the
    write. The driver's message is never exposed.
    """
    return validation_response({
        "parent_reference": "One or more referenced parent records no longer exist"
    })


def vessel_exists(cursor, vessel_id):
    """Return True when the research vessel exists."""
    cursor.execute(
        "SELECT 1 AS present FROM research_vessel WHERE vessel_id = %s",
        (vessel_id,)
    )
    return cursor.fetchone() is not None


def fetch_expedition(cursor, expedition_id):
    """Return one joined expedition row, or None when the id does not exist."""
    cursor.execute(
        EXPEDITION_SELECT + " WHERE e.expedition_id = %s",
        (expedition_id,)
    )
    return cursor.fetchone()


def count_missions(cursor, expedition_id):
    """Count the missions belonging to this expedition."""
    cursor.execute(
        "SELECT COUNT(*) AS mission_count FROM mission WHERE expedition_id = %s",
        (expedition_id,)
    )
    return int(cursor.fetchone()["mission_count"])


def count_missions_outside_range(cursor, expedition_id, start_date, end_date):
    """Count this expedition's missions that a new date range would exclude.

    A mission is outside the proposed range when its start date, or its
    non-null end date, falls before start_date or after end_date. Missions
    that are still running (end_time IS NULL) are judged on start date alone.
    """
    cursor.execute(
        """
        SELECT COUNT(*) AS outside_count
          FROM mission
         WHERE expedition_id = %s
           AND (
                 DATE(start_time) < %s
              OR DATE(start_time) > %s
              OR (end_time IS NOT NULL
                  AND (DATE(end_time) < %s OR DATE(end_time) > %s))
               )
        """,
        (expedition_id, start_date, end_date, start_date, end_date)
    )
    return int(cursor.fetchone()["outside_count"])


def not_found_response():
    """Build the standard HTTP 404 body for a missing expedition."""
    return jsonify({
        "success": False,
        "message": "Expedition not found"
    }), 404


def build_expedition_payload(expedition_id, cleaned, vessel_name, home_port,
                             mission_count):
    """Build the response body for a freshly created or updated expedition."""
    return {
        "expedition_id": expedition_id,
        "vessel_id": cleaned["vessel_id"],
        "vessel_name": vessel_name,
        "home_port": home_port,
        "title": cleaned["title"],
        "start_date": date_to_iso(cleaned["start_date"]),
        "end_date": date_to_iso(cleaned["end_date"]),
        "objective": cleaned["objective"],
        "status": cleaned["status"],
        "budget": decimal_to_number(cleaned["budget"]),
        "mission_count": mission_count,
    }


def fetch_vessel_details(cursor, vessel_id):
    """Return (vessel_name, home_port) for an existing vessel, or None."""
    cursor.execute(
        "SELECT vessel_name, home_port FROM research_vessel WHERE vessel_id = %s",
        (vessel_id,)
    )
    row = cursor.fetchone()
    if row is None:
        return None
    return row["vessel_name"], row["home_port"]


# ============================================================================
# ENDPOINT 1 - list all expeditions
# ============================================================================

@expeditions_bp.route("", methods=["GET"])
def list_expeditions():
    """GET /api/expeditions - every expedition, joined, by expedition_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(EXPEDITION_SELECT + " ORDER BY e.expedition_id")
        rows = cursor.fetchall()

        expeditions = [serialize_expedition(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(expeditions),
            "data": expeditions
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one expedition
# ============================================================================

@expeditions_bp.route("/<int:expedition_id>", methods=["GET"])
def get_expedition(expedition_id):
    """GET /api/expeditions/<id> - one joined expedition, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_expedition(cursor, expedition_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_expedition(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create an expedition
# ============================================================================

@expeditions_bp.route("", methods=["POST"])
def create_expedition():
    """POST /api/expeditions - validate, check the vessel, insert."""
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_expedition_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # Existence check first, so a bad vessel_id is a clear field error
        # rather than a raw driver failure.
        vessel = fetch_vessel_details(cursor, cleaned["vessel_id"])
        if vessel is None:
            connection.rollback()
            return validation_response({
                "vessel_id": "vessel_id does not reference an existing research vessel"
            })

        vessel_name, home_port = vessel

        cursor.execute(
            """
            INSERT INTO expedition
                (vessel_id, title, start_date, end_date, objective, status, budget)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            (
                cleaned["vessel_id"],
                cleaned["title"],
                cleaned["start_date"],
                cleaned["end_date"],
                cleaned["objective"],
                cleaned["status"],
                cleaned["budget"],
            )
        )
        new_id = cursor.lastrowid
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Expedition created successfully",
            # A brand-new expedition has no missions yet.
            "data": build_expedition_payload(
                new_id, cleaned, vessel_name, home_port, 0
            )
        }), 201

    except MySQLError as err:
        safe_rollback(connection)

        # Concurrency fallback: the vessel was deleted between the check above
        # and this INSERT.
        if err.errno == errorcode.ER_NO_REFERENCED_ROW_2:
            return parent_reference_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


