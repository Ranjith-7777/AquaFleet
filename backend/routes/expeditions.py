@expeditions_bp.route("/<int:expedition_id>", methods=["DELETE"])
def delete_expedition(expedition_id):
    """DELETE /api/expeditions/<id> - only when it contains no missions.

    fk_mission_expedition cascades, and each mission cascades again into six
    further tables plus sample_aliquot, so a single DELETE here could destroy
    dozens of rows across eight tables with no error raised. This endpoint
    refuses instead and reports how many missions are in the way; clearing
    them is a separate, deliberate act through the mission API, where each
    mission has its own guard.

    On one connection inside one transaction:

        1. lock the expedition row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count missions
        4. 409 with the count if non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        cursor.execute(
            "SELECT expedition_id FROM expedition WHERE expedition_id = %s FOR UPDATE",
            (expedition_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        mission_count = count_missions(cursor, expedition_id)

        if mission_count > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Expedition cannot be deleted because it contains "
                           "one or more missions",
                "dependencies": {
                    "missions": mission_count
                }
            }), 409

        cursor.execute(
            "DELETE FROM expedition WHERE expedition_id = %s",
            (expedition_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Expedition deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch: fk_mission_expedition cascades, so MySQL never
        # raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
