# ENDPOINT 4 - replace a mission
# ============================================================================

@missions_bp.route("/<int:mission_id>", methods=["PUT"])
def update_mission(mission_id):
    """PUT /api/missions/<id> - full replacement of the seven columns.

    Only the mission row is touched. The six child tables - vehicle and
    operator assignments, telemetry, samples, incidents and inspection tasks -
    are never read or modified here.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_mission_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it underneath the rewrite.
        cursor.execute(
            "SELECT mission_id FROM mission WHERE mission_id = %s FOR UPDATE",
            (mission_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        expedition_row, zone_row, parent_errors = load_parents(cursor, cleaned)
        if parent_errors:
            connection.rollback()
            return validation_response(parent_errors)

        cross_errors = validate_against_parents(cleaned, expedition_row, zone_row)
        if cross_errors:
            connection.rollback()
            return validation_response(cross_errors)

        cursor.execute(
            """
            UPDATE mission
               SET expedition_id = %s,
                   zone_id       = %s,
                   mission_type  = %s,
                   start_time    = %s,
                   end_time      = %s,
                   depth_target  = %s,
                   status        = %s
             WHERE mission_id = %s
            """,
            (
                cleaned["expedition_id"],
                cleaned["zone_id"],
                cleaned["mission_type"],
                cleaned["start_time"],
                cleaned["end_time"],
                cleaned["depth_target"],
                cleaned["status"],
                mission_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Mission updated successfully",
            "data": build_mission_payload(
                mission_id, cleaned, expedition_row, zone_row
            )
        }), 200

    except MySQLError as err:
        safe_rollback(connection)

        if err.errno == errorcode.ER_NO_REFERENCED_ROW_2:
            return parent_reference_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - protected delete
# ============================================================================

@missions_bp.route("/<int:mission_id>", methods=["DELETE"])
def delete_mission(mission_id):
    """DELETE /api/missions/<id> - only when nothing references the mission.

    All six child foreign keys cascade, so MySQL would happily erase the
    mission's vehicle assignments, operator staffing, telemetry log, collected
    samples - and, through those, their aliquots - incidents and inspection
    findings, without raising error 1451. This endpoint refuses instead and
    reports every count, including the zeroes.

    On one connection inside one transaction:

        1. lock the mission row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count all six child tables
        4. 409 with the counts if the total is non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT

    There is deliberately no force-delete option, and child rows are never
    removed by this API.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()

        # Be explicit rather than relying on the driver's default, so the
        # lock taken below is definitely held until commit or rollback.
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        cursor.execute(
            "SELECT mission_id FROM mission WHERE mission_id = %s FOR UPDATE",
            (mission_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        dependencies = count_dependencies(cursor, mission_id)

        if dependencies["total"] > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Mission cannot be deleted because it has related "
                           "operational records",
                "dependencies": dependencies
            }), 409

        cursor.execute(
            "DELETE FROM mission WHERE mission_id = %s",
            (mission_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Mission deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch: every child foreign key cascades, so MySQL never
        # raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
