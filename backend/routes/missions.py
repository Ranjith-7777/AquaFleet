@missions_bp.route("", methods=["GET"])
def list_missions():
    """GET /api/missions - every mission, joined, ordered by mission_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(MISSION_SELECT + " ORDER BY m.mission_id")
        rows = cursor.fetchall()

        missions = [serialize_mission(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(missions),
            "data": missions
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one mission
# ============================================================================

@missions_bp.route("/<int:mission_id>", methods=["GET"])
def get_mission(mission_id):
    """GET /api/missions/<id> - one joined mission, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_mission(cursor, mission_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_mission(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a mission
# ============================================================================

@missions_bp.route("", methods=["POST"])
def create_mission():
    """POST /api/missions - validate locally, then against both parents.

    Parent lookup and the cross-table rules run inside the same transaction as
    the INSERT, so the expedition window and zone band cannot change between
    being read and being relied upon.
    """
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_mission_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        expedition_row, zone_row, parent_errors = load_parents(cursor, cleaned)
        if parent_errors:
            connection.rollback()
            return validation_response(parent_errors)

        cross_errors = validate_against_parents(cleaned, expedition_row, zone_row)
        if cross_errors:
            connection.rollback()
            return validation_response(cross_errors)

        cursor.execute(
            """
            INSERT INTO mission
                (expedition_id, zone_id, mission_type, start_time, end_time,
                 depth_target, status)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            (
                cleaned["expedition_id"],
                cleaned["zone_id"],
                cleaned["mission_type"],
                cleaned["start_time"],
                cleaned["end_time"],
                cleaned["depth_target"],
                cleaned["status"],
            )
        )
        new_id = cursor.lastrowid
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Mission created successfully",
            "data": build_mission_payload(new_id, cleaned, expedition_row, zone_row)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)

        # Concurrency fallback: a parent was deleted between the checks above
        # and this INSERT.
        if err.errno == errorcode.ER_NO_REFERENCED_ROW_2:
            return parent_reference_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


