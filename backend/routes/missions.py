"""
routes/missions.py
------------------
CRUD REST API for the `mission` table.

    GET    /api/missions             list every mission
    GET    /api/missions/<id>        fetch one mission
    POST   /api/missions             create a mission
    PUT    /api/missions/<id>        replace a mission
    DELETE /api/missions/<id>        delete a mission with no operational records

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, commit/rollback around
writes, cleanup in finally blocks, full error logging server-side and a
generic message to the client.

`mission` is the most connected table in the schema - two parents and six
children - so four things differ from every earlier module.

1. DATETIME handling. start_time and end_time are the project's first DATETIME
   columns, accepted and emitted strictly as "YYYY-MM-DD HH:MM:SS". The ISO
   "T" separator, timezone suffixes and missing seconds are all rejected.

2. end_time is genuinely nullable. The key is REQUIRED on both POST and PUT,
   but JSON null is a valid value meaning "still running". Absence and null
   are therefore different things and are handled separately.

3. Cross-table business rules that the schema cannot express. A mission must
   sit inside its expedition's date range and within its zone's depth band,
   and its status must agree with whether end_time is set. All three are
   checked against freshly read parent rows inside the write transaction.

4. duration_minutes is DERIVED, never stored. There is no such column; it is
   computed with TIMESTAMPDIFF and is null whenever end_time is null.

PROTECTED DELETE
----------------
All six child tables cascade, so deleting a mission would silently destroy its
vehicle assignments, operator staffing, telemetry, samples (and their aliquots,
transitively), incidents and inspection findings, with no error raised. This
API refuses whenever any of them holds a row, and reports every count.

There is no duplicate handling: `mission` has no UNIQUE constraint, so MySQL
error 1062 is unreachable here.
"""

import math
from datetime import datetime
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

missions_bp = Blueprint("missions", __name__, url_prefix="/api/missions")


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

MISSION_TYPE_MAX_LENGTH = 80

# Must match chk_mission_status in schema.sql exactly, including the casing.
MISSION_STATUSES = ("Planned", "In Progress", "Completed", "Aborted")

# Statuses that describe a finished mission, so end_time must be present.
STATUSES_REQUIRING_END_TIME = ("Completed", "Aborted")

# Statuses that describe a mission not yet finished, so end_time must be null.
STATUSES_REQUIRING_NULL_END_TIME = ("Planned", "In Progress")

# depth_target is DECIMAL(8,2): 8 total digits, 2 of them after the point.
MAX_DEPTH_VALUE = Decimal("999999.99")
DECIMAL_PLACES = 2

# The one and only accepted datetime format, in and out.
DATETIME_FORMAT = "%Y-%m-%d %H:%M:%S"
DATETIME_FORMAT_MESSAGE = "must be a valid datetime in YYYY-MM-DD HH:MM:SS format"

# Every field a client may send. mission_id is generated by MySQL.
ALLOWED_FIELDS = {
    "expedition_id", "zone_id", "mission_type",
    "start_time", "end_time", "depth_target", "status"
}

# One statement covers both parent joins and the derived duration.
MISSION_SELECT = """
    SELECT m.mission_id,
           m.expedition_id,
           e.title AS expedition_title,
           m.zone_id,
           z.zone_name,
           z.region,
           m.mission_type,
           m.start_time,
           m.end_time,
           TIMESTAMPDIFF(MINUTE, m.start_time, m.end_time) AS duration_minutes,
           m.depth_target,
           m.status
      FROM mission m
      JOIN expedition  e ON e.expedition_id = m.expedition_id
      JOIN marine_zone z ON z.zone_id       = m.zone_id
"""

# The six tables that reference mission(mission_id), paired with the key each
# one uses in the 409 response. Both the table names and the SQL are fixed
# literals here - nothing is ever built from request data.
DEPENDENCY_QUERIES = (
    ("vehicle_assignments",
     "SELECT COUNT(*) AS dependency_count FROM mission_vehicle WHERE mission_id = %s"),
    ("operator_assignments",
     "SELECT COUNT(*) AS dependency_count FROM mission_operator WHERE mission_id = %s"),
    ("telemetry_points",
     "SELECT COUNT(*) AS dependency_count FROM telemetry_point WHERE mission_id = %s"),
    ("samples",
     "SELECT COUNT(*) AS dependency_count FROM sample WHERE mission_id = %s"),
    ("incidents",
     "SELECT COUNT(*) AS dependency_count FROM incident WHERE mission_id = %s"),
    ("inspection_tasks",
     "SELECT COUNT(*) AS dependency_count FROM inspection_task WHERE mission_id = %s"),
)

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Mission %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every depth read back from
    MySQL passes through here.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def datetime_to_text(value):
    """Render a DATETIME as YYYY-MM-DD HH:MM:SS, or None.

    The driver returns datetime.datetime, which Flask would otherwise
    serialize as an RFC 1123 string. A null end_time stays JSON null.
    """
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.strftime(DATETIME_FORMAT)
    return value


def serialize_mission(row):
    """Convert one joined database row into a JSON-safe dict."""
    if row is None:
        return None

    duration = row["duration_minutes"]

    return {
        "mission_id": row["mission_id"],
        "expedition_id": row["expedition_id"],
        "expedition_title": row["expedition_title"],
        "zone_id": row["zone_id"],
        "zone_name": row["zone_name"],
        "region": row["region"],
        "mission_type": row["mission_type"],
        "start_time": datetime_to_text(row["start_time"]),
        "end_time": datetime_to_text(row["end_time"]),
        # TIMESTAMPDIFF returns NULL when end_time is NULL, which stays null
        # rather than becoming 0. The value is never stored.
        "duration_minutes": None if duration is None else int(duration),
        "depth_target": decimal_to_number(row["depth_target"]),
        "status": row["status"],
    }


def parse_positive_integer(field, value, errors):
    """Validate a foreign-key id: a genuine JSON integer greater than zero."""
    message = f"{field} must be an integer greater than 0"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise pass as 1.
    if isinstance(value, bool):
        errors[field] = message
        return None

    # A genuine integer only: 2.0 arrives as a float and is rejected, as are
    # strings, lists and dicts.
    if not isinstance(value, int):
        errors[field] = message
        return None

    if value <= 0:
        errors[field] = message
        return None

    return value


def parse_datetime(field, value, errors):
    """Validate a DATETIME strictly and return a datetime, or None.

    Only the exact form YYYY-MM-DD HH:MM:SS is accepted. strptime alone would
    also swallow "2026-9-20 7:00:00", so the parsed result is formatted back
    and compared against what was submitted. strptime itself rejects the ISO
    "T" separator, timezone suffixes, missing seconds, fractional seconds and
    impossible calendar dates such as 2026-02-30 25:00:00.
    """
    if not isinstance(value, str):
        errors[field] = f"{field} must be a string"
        return None

    trimmed = value.strip()
    if not trimmed:
        errors[field] = f"{field} must not be empty"
        return None

    try:
        parsed = datetime.strptime(trimmed, DATETIME_FORMAT)
    except ValueError:
        errors[field] = f"{field} {DATETIME_FORMAT_MESSAGE}"
        return None

    if parsed.strftime(DATETIME_FORMAT) != trimmed:
        errors[field] = f"{field} {DATETIME_FORMAT_MESSAGE}"
        return None

    return parsed


def parse_depth_target(value, errors):
    """Validate depth_target and return it as a Decimal, or None."""
    field = "depth_target"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_DEPTH_VALUE:
        errors[field] = f"{field} must not exceed {MAX_DEPTH_VALUE}"
        return None

    # chk_mission_depth allows zero - a surface mission is legitimate.
    if parsed < 0:
        errors[field] = f"{field} must be greater than or equal to 0"
        return None

    return parsed


def validate_mission_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    Only local rules are applied here: types, formats, the enum, end_time
    ordering and status/end_time consistency. Whether the parents exist, and
    whether the mission fits their date range and depth band, is settled later
    inside the write transaction.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Parent ids: genuine positive integers. ---
    expedition_id = parse_positive_integer(
        "expedition_id", payload.get("expedition_id"), errors
    )
    if expedition_id is not None:
        cleaned["expedition_id"] = expedition_id

    zone_id = parse_positive_integer("zone_id", payload.get("zone_id"), errors)
    if zone_id is not None:
        cleaned["zone_id"] = zone_id

    # --- mission_type: required, non-blank string, length-limited. ---
    mission_type = payload.get("mission_type")
    if mission_type is None:
        errors["mission_type"] = "mission_type is required"
    elif not isinstance(mission_type, str):
        errors["mission_type"] = "mission_type must be a string"
    else:
        trimmed_type = mission_type.strip()
        if not trimmed_type:
            errors["mission_type"] = "mission_type must not be empty"
        elif len(trimmed_type) > MISSION_TYPE_MAX_LENGTH:
            errors["mission_type"] = (
                f"mission_type must be at most {MISSION_TYPE_MAX_LENGTH} characters"
            )
        else:
            cleaned["mission_type"] = trimmed_type

    # --- start_time: required, non-null, strict format. ---
    start_time = None
    if "start_time" not in payload or payload.get("start_time") is None:
        errors["start_time"] = "start_time is required"
    else:
        start_time = parse_datetime("start_time", payload["start_time"], errors)
        if start_time is not None:
            cleaned["start_time"] = start_time

    # --- end_time: the KEY is required, but null is a valid value. ---
    end_time = None
    end_time_present = "end_time" in payload

    if not end_time_present:
        # Absence is an error; an explicit null is not. The two cases cannot be
        # distinguished with payload.get(), hence the membership test.
        errors["end_time"] = "end_time is required and may be null"
    elif payload["end_time"] is None:
        # A running or planned mission has no end time yet.
        cleaned["end_time"] = None
    else:
        end_time = parse_datetime("end_time", payload["end_time"], errors)
        if end_time is not None:
            # chk_mission_times is strictly greater, so equality is invalid.
            if start_time is not None and end_time <= start_time:
                errors["end_time"] = "end_time must be later than start_time"
            else:
                cleaned["end_time"] = end_time

    # --- depth_target: numeric, finite, >= 0, <= 999999.99, 2 decimals. ---
    depth_target = parse_depth_target(payload.get("depth_target"), errors)
    if depth_target is not None:
        cleaned["depth_target"] = depth_target

    # --- status: exact match against the CHECK list. ---
    status = payload.get("status")
    trimmed_status = None

    if status is None:
        errors["status"] = "status is required"
    elif not isinstance(status, str):
        errors["status"] = "status must be a string"
    else:
        candidate = status.strip()
        if not candidate:
            errors["status"] = "status must not be empty"
        elif candidate not in MISSION_STATUSES:
            # Case is significant: 'completed' is rejected, never corrected.
            errors["status"] = f"status must be one of: {', '.join(MISSION_STATUSES)}"
        else:
            trimmed_status = candidate
            cleaned["status"] = candidate

    # --- status must agree with whether end_time is set. ---
    # Only checkable once both fields are individually valid, and only when
    # end_time has not already produced an error of its own.
    if trimmed_status is not None and end_time_present and "end_time" not in errors:
        has_end_time = cleaned.get("end_time") is not None

        if trimmed_status in STATUSES_REQUIRING_END_TIME and not has_end_time:
            errors["end_time"] = (
                f"end_time must not be null when status is {trimmed_status}"
            )
        elif trimmed_status in STATUSES_REQUIRING_NULL_END_TIME and has_end_time:
            errors["end_time"] = (
                f"end_time must be null when status is {trimmed_status}"
            )

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def parent_reference_response():
    """Build the HTTP 400 body for a MySQL 1452 foreign-key failure.

    Reached only if a parent is deleted between the existence check and the
    write. The driver's message is never exposed.
    """
    return validation_response({
        "parent_reference": "One or more referenced parent records no longer exist"
    })


def fetch_expedition_window(cursor, expedition_id):
    """Return the expedition's title and date range, or None when absent."""
    cursor.execute(
        """
        SELECT title, start_date, end_date
          FROM expedition
         WHERE expedition_id = %s
        """,
        (expedition_id,)
    )
    return cursor.fetchone()


def fetch_zone_band(cursor, zone_id):
    """Return the zone's name, region and depth band, or None when absent."""
    cursor.execute(
        """
        SELECT zone_name, region, min_depth, max_depth
          FROM marine_zone
         WHERE zone_id = %s
        """,
        (zone_id,)
    )
    return cursor.fetchone()


def validate_against_parents(cleaned, expedition_row, zone_row):
    """Apply the cross-table rules the schema cannot express.

    Returns an errors dict, empty when everything fits. Both parent rows must
    already be known to exist.
    """
    errors = {}

    window_start = expedition_row["start_date"]
    window_end = expedition_row["end_date"]

    # The mission must begin on a day inside the expedition, inclusive. Only
    # the DATE part matters: any time on a boundary day is acceptable.
    start_day = cleaned["start_time"].date()
    if not (window_start <= start_day <= window_end):
        errors["start_time"] = (
            f"start_time date must fall within the expedition date range "
            f"{window_start.isoformat()} to {window_end.isoformat()}"
        )

    end_time = cleaned.get("end_time")
    if end_time is not None:
        end_day = end_time.date()
        if not (window_start <= end_day <= window_end):
            errors["end_time"] = (
                f"end_time date must fall within the expedition date range "
                f"{window_start.isoformat()} to {window_end.isoformat()}"
            )

    # The target depth must sit inside the zone's band, inclusive.
    min_depth = zone_row["min_depth"]
    max_depth = zone_row["max_depth"]
    depth_target = cleaned["depth_target"]

    if not (min_depth <= depth_target <= max_depth):
        errors["depth_target"] = (
            f"depth_target must be between {min_depth} and {max_depth} "
            f"for the selected marine zone"
        )

    return errors


def load_parents(cursor, cleaned):
    """Fetch both parents and return (expedition_row, zone_row, errors).

    Missing parents are reported as field-level validation errors rather than
    being left to the driver's foreign-key failure.
    """
    errors = {}

    expedition_row = fetch_expedition_window(cursor, cleaned["expedition_id"])
    if expedition_row is None:
        errors["expedition_id"] = (
            "expedition_id does not reference an existing expedition"
        )

    zone_row = fetch_zone_band(cursor, cleaned["zone_id"])
    if zone_row is None:
        errors["zone_id"] = "zone_id does not reference an existing marine zone"

    return expedition_row, zone_row, errors


def count_dependencies(cursor, mission_id):
    """Count the rows in every child table that points at this mission.

    Returns a dict using the response key names, plus a "total" of the six
    direct counts. Zero counts are included so the client always sees the full
    picture. Each statement is a fixed literal with the id bound as a
    parameter.
    """
    counts = {}
    total = 0

    for response_key, sql in DEPENDENCY_QUERIES:
        cursor.execute(sql, (mission_id,))
        count = int(cursor.fetchone()["dependency_count"])
        counts[response_key] = count
        total += count

    counts["total"] = total
    return counts


def fetch_mission(cursor, mission_id):
    """Return one joined mission row, or None when the id does not exist."""
    cursor.execute(
        MISSION_SELECT + " WHERE m.mission_id = %s",
        (mission_id,)
    )
    return cursor.fetchone()


def not_found_response():
    """Build the standard HTTP 404 body for a missing mission."""
    return jsonify({
        "success": False,
        "message": "Mission not found"
    }), 404


def build_mission_payload(mission_id, cleaned, expedition_row, zone_row):
    """Build the response body for a freshly created or updated mission.

    duration_minutes is computed here from the validated values rather than
    read back from MySQL, and is null whenever end_time is null. It is never
    written to any column.
    """
    end_time = cleaned.get("end_time")

    if end_time is None:
        duration_minutes = None
    else:
        delta = end_time - cleaned["start_time"]
        # Matches TIMESTAMPDIFF(MINUTE, ...), which truncates toward zero.
        duration_minutes = int(delta.total_seconds() // 60)

    return {
        "mission_id": mission_id,
        "expedition_id": cleaned["expedition_id"],
        "expedition_title": expedition_row["title"],
        "zone_id": cleaned["zone_id"],
        "zone_name": zone_row["zone_name"],
        "region": zone_row["region"],
        "mission_type": cleaned["mission_type"],
        "start_time": cleaned["start_time"].strftime(DATETIME_FORMAT),
        "end_time": None if end_time is None else end_time.strftime(DATETIME_FORMAT),
        "duration_minutes": duration_minutes,
        "depth_target": decimal_to_number(cleaned["depth_target"]),
        "status": cleaned["status"],
    }


