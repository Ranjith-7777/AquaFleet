"""
routes/vehicles.py
------------------
CRUD REST API for the `auv_rov` table (autonomous underwater vehicles and
remotely operated vehicles).

    GET    /api/vehicles             list every vehicle
    GET    /api/vehicles/<id>        fetch one vehicle
    POST   /api/vehicles             create a vehicle
    PUT    /api/vehicles/<id>        replace a vehicle
    DELETE /api/vehicles/<id>        delete a vehicle, if nothing references it

This module follows the same conventions as routes/vessels.py and
routes/marine_zones.py: parameterized SQL, dictionary cursors for reads,
commit/rollback around writes, cleanup in finally blocks, full error logging
server-side and a generic message to the client.

PROTECTED DELETE
----------------
The four child tables - mission_vehicle, vehicle_sensor, vehicle_battery and
maintenance_record - all declare ON DELETE CASCADE, so MySQL would happily
erase a vehicle's entire operational history along with the vehicle itself and
would never raise error 1451.

That is not acceptable for an operations database, so this API applies a
deliberately stricter rule than the schema: a vehicle with any dependent row
cannot be deleted at all. The check and the delete run inside one transaction,
with the vehicle row locked FOR UPDATE, so the window between counting and
deleting is as small as practical. There is no override flag.
"""

import math
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

vehicles_bp = Blueprint("vehicles", __name__, url_prefix="/api/vehicles")


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Free-text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "vehicle_name": 100,
    "model": 100,
}

# Must match chk_vehicle_type in schema.sql exactly, including the casing.
VEHICLE_TYPES = ("AUV", "ROV")

# Must match chk_vehicle_status in schema.sql exactly, including the casing.
VEHICLE_STATUSES = ("Available", "Deployed", "Maintenance", "Retired")

# Every field a client may send. vehicle_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | {"vehicle_type", "max_depth", "status"}

# max_depth is DECIMAL(8,2): 8 total digits, 2 of them after the point.
MAX_DEPTH_VALUE = Decimal("999999.99")
DECIMAL_PLACES = 2

# Columns selected by every read, in a fixed order.
VEHICLE_COLUMNS = "vehicle_id, vehicle_name, vehicle_type, model, max_depth, status"

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"

# The four tables that reference auv_rov(vehicle_id), paired with the key each
# one uses in the 409 response. Both the table names and the SQL are fixed
# literals here - nothing is ever built from request data.
DEPENDENCY_QUERIES = (
    ("mission_assignments",
     "SELECT COUNT(*) AS dependency_count FROM mission_vehicle WHERE vehicle_id = %s"),
    ("sensor_assignments",
     "SELECT COUNT(*) AS dependency_count FROM vehicle_sensor WHERE vehicle_id = %s"),
    ("battery_assignments",
     "SELECT COUNT(*) AS dependency_count FROM vehicle_battery WHERE vehicle_id = %s"),
    ("maintenance_records",
     "SELECT COUNT(*) AS dependency_count FROM maintenance_record WHERE vehicle_id = %s"),
)


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Vehicle %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every max_depth read back
    from MySQL passes through here. float() is safe at this point because the
    value is already constrained to 8 digits with 2 decimal places.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def serialize_vehicle(row):
    """Convert one database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "vehicle_id": row["vehicle_id"],
        "vehicle_name": row["vehicle_name"],
        "vehicle_type": row["vehicle_type"],
        "model": row["model"],
        "max_depth": decimal_to_number(row["max_depth"]),
        "status": row["status"],
    }


def build_vehicle_payload(vehicle_id, cleaned):
    """Build the response body for a freshly created or updated vehicle."""
    return {
        "vehicle_id": vehicle_id,
        "vehicle_name": cleaned["vehicle_name"],
        "vehicle_type": cleaned["vehicle_type"],
        "model": cleaned["model"],
        "max_depth": decimal_to_number(cleaned["max_depth"]),
        "status": cleaned["status"],
    }


def parse_max_depth(value, errors):
    """Validate max_depth and return it as a Decimal, or None.

    Records its own problem in `errors` and returns None when the value is
    unusable, so the caller can keep collecting the remaining errors.
    """
    field = "max_depth"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise be accepted
    # and stored as a depth of 1.
    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    # Rejects strings such as "100" as well as lists, dicts and null.
    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        # Decimal(value) on a float would introduce binary rounding noise and
        # make the decimal-place check meaningless.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    # exponent -3 means three digits after the point, and so on.
    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_DEPTH_VALUE:
        errors[field] = f"{field} must not exceed {MAX_DEPTH_VALUE}"
        return None

    # chk_vehicle_max_depth is strictly greater than zero, so 0 is rejected.
    if parsed <= 0:
        errors[field] = f"{field} must be greater than 0"
        return None

    return parsed


def parse_choice(field, value, allowed, errors):
    """Validate a trimmed, case-sensitive match against a fixed list."""
    if value is None:
        errors[field] = f"{field} is required"
        return None

    if not isinstance(value, str):
        errors[field] = f"{field} must be a string"
        return None

    trimmed = value.strip()
    if not trimmed:
        errors[field] = f"{field} must not be empty"
        return None

    if trimmed not in allowed:
        # Case is significant: 'auv' is rejected rather than corrected, so a
        # client typo never turns into a silently different value.
        errors[field] = f"{field} must be one of: {', '.join(allowed)}"
        return None

    return trimmed


def validate_vehicle_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` holds trimmed text and a Decimal max_depth ready to be
    used as SQL parameters. When `errors` is non-empty the caller must reject
    the request with HTTP 400. All problems are collected in one pass.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Free-text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- Constrained text fields, matching the CHECK lists exactly. ---
    vehicle_type = parse_choice(
        "vehicle_type", payload.get("vehicle_type"), VEHICLE_TYPES, errors
    )
    if vehicle_type is not None:
        cleaned["vehicle_type"] = vehicle_type

    status = parse_choice(
        "status", payload.get("status"), VEHICLE_STATUSES, errors
    )
    if status is not None:
        cleaned["status"] = status

    # --- max_depth: numeric, finite, > 0, in range, at most 2 decimals. ---
    max_depth = parse_max_depth(payload.get("max_depth"), errors)
    if max_depth is not None:
        cleaned["max_depth"] = max_depth

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_vehicle(cursor, vehicle_id):
    """Return one vehicle row, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {VEHICLE_COLUMNS} FROM auv_rov WHERE vehicle_id = %s",
        (vehicle_id,)
    )
    return cursor.fetchone()


def count_dependencies(cursor, vehicle_id):
    """Count the rows in every child table that point at this vehicle.

    Returns a dict using the response key names, plus a "total". Zero counts
    are included so the client always sees the full picture. Each statement
    is a fixed literal with the id supplied as a bound parameter.
    """
    counts = {}
    total = 0

    for response_key, sql in DEPENDENCY_QUERIES:
        cursor.execute(sql, (vehicle_id,))
        count = int(cursor.fetchone()["dependency_count"])
        counts[response_key] = count
        total += count

    counts["total"] = total
    return counts


def not_found_response():
    """Build the standard HTTP 404 body for a missing vehicle."""
    return jsonify({
        "success": False,
        "message": "AUV/ROV vehicle not found"
    }), 404


def duplicate_name_response():
    """Build the standard HTTP 409 body for a UNIQUE(vehicle_name) violation."""
    return jsonify({
        "success": False,
        "message": "An AUV/ROV vehicle with this name already exists"
    }), 409


# ============================================================================
# ENDPOINT 1 - list all vehicles
# ============================================================================

@vehicles_bp.route("", methods=["GET"])
def list_vehicles():
    """GET /api/vehicles - every vehicle, ordered by vehicle_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {VEHICLE_COLUMNS} FROM auv_rov ORDER BY vehicle_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        vehicles = [serialize_vehicle(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(vehicles),
            "data": vehicles
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one vehicle
# ============================================================================

@vehicles_bp.route("/<int:vehicle_id>", methods=["GET"])
def get_vehicle(vehicle_id):
    """GET /api/vehicles/<id> - one vehicle, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_vehicle(cursor, vehicle_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_vehicle(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a vehicle
# ============================================================================

@vehicles_bp.route("", methods=["POST"])
def create_vehicle():
    """POST /api/vehicles - validate, insert, return the new row."""
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_vehicle_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        # The Decimal is passed straight through as a parameter; the driver
        # renders it without any float round-trip.
        cursor.execute(
            """
            INSERT INTO auv_rov (vehicle_name, vehicle_type, model, max_depth, status)
            VALUES (%s, %s, %s, %s, %s)
            """,
            (
                cleaned["vehicle_name"],
                cleaned["vehicle_type"],
                cleaned["model"],
                cleaned["max_depth"],
                cleaned["status"],
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "AUV/ROV vehicle created successfully",
            "data": build_vehicle_payload(cursor.lastrowid, cleaned)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)

        # Letting MySQL detect the duplicate - rather than doing a SELECT
        # first - is what makes this correct when two requests race.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace a vehicle
# ============================================================================

@vehicles_bp.route("/<int:vehicle_id>", methods=["PUT"])
def update_vehicle(vehicle_id):
    """PUT /api/vehicles/<id> - full replacement of the five columns.

    Only the auv_rov row is touched. Child records in mission_vehicle,
    vehicle_sensor, vehicle_battery and maintenance_record are never read,
    modified or removed by an update.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so all five fields are required, exactly
    # as they are for POST.
    cleaned, errors = validate_vehicle_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_vehicle(cursor, vehicle_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE auv_rov
               SET vehicle_name = %s,
                   vehicle_type = %s,
                   model        = %s,
                   max_depth    = %s,
                   status       = %s
             WHERE vehicle_id = %s
            """,
            (
                cleaned["vehicle_name"],
                cleaned["vehicle_type"],
                cleaned["model"],
                cleaned["max_depth"],
                cleaned["status"],
                vehicle_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "AUV/ROV vehicle updated successfully",
            "data": build_vehicle_payload(vehicle_id, cleaned)
        }), 200

    except MySQLError as err:
        safe_rollback(connection)

        # Renaming a vehicle to a name another vehicle already uses.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - protected delete
# ============================================================================

@vehicles_bp.route("/<int:vehicle_id>", methods=["DELETE"])
def delete_vehicle(vehicle_id):
    """DELETE /api/vehicles/<id> - only when nothing references the vehicle.

    The schema would cascade, silently destroying mission assignments, sensor
    mountings, battery cycles and maintenance history. This endpoint refuses
    instead, and reports exactly what is in the way.

    Everything below happens on one connection inside one transaction:

        1. lock the vehicle row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count the rows in all four child tables
        4. 409 with the counts if any of them is non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT

    There is deliberately no query parameter that skips step 4.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()

        # Be explicit rather than relying on the driver's default, so the
        # lock taken below is definitely held until commit or rollback.
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete or rename it underneath us.
        cursor.execute(
            "SELECT vehicle_id FROM auv_rov WHERE vehicle_id = %s FOR UPDATE",
            (vehicle_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        dependencies = count_dependencies(cursor, vehicle_id)

        if dependencies["total"] > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "AUV/ROV vehicle cannot be deleted because it has "
                           "related operational records",
                "dependencies": dependencies
            }), 409

        cursor.execute(
            "DELETE FROM auv_rov WHERE vehicle_id = %s",
            (vehicle_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "AUV/ROV vehicle deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch here: the child foreign keys use ON DELETE CASCADE,
        # so MySQL never raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
