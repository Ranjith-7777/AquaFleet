"""
routes/battery_packs.py
-----------------------
CRUD REST API for the `battery_pack` table.

    GET    /api/battery-packs             list every battery pack
    GET    /api/battery-packs/<id>        fetch one battery pack
    POST   /api/battery-packs             create a battery pack
    PUT    /api/battery-packs/<id>        replace a battery pack
    DELETE /api/battery-packs/<id>        delete a pack with no assignment history

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, commit/rollback around
writes, cleanup in finally blocks, full error logging server-side and a
generic message to the client.

FOUR THINGS WORTH KNOWING
-------------------------
1. No duplicate handling. `battery_pack` has no UNIQUE constraint - the primary
   key is its only index - so identical rows are legal and expected: each row
   is a distinct physical pack. MySQL error 1062 is unreachable here, so there
   is deliberately no 409-on-duplicate branch.

2. capacity_wh is DECIMAL(10,2), a third distinct precision in this project
   after DECIMAL(8,2) for depths and DECIMAL(6,3) for sensor accuracy. Its
   ceiling is 99999999.99, so the constants from the other modules do not
   carry over.

3. cycle_count is the project's first plain INT payload field, and the first
   numeric field whose CHECK allows zero (chk_battery_cycles is >= 0, while
   every other numeric column is > 0). A brand-new pack legitimately has zero
   cycles. It also has a column DEFAULT, so POST treats it as optional while
   PUT - being a full replacement - requires it.

PROTECTED DELETE
----------------
vehicle_battery declares ON DELETE CASCADE, so MySQL would quietly erase the
record of which vehicle carried this pack and when, and would never raise
error 1451. Those rows are operational history - the composite primary key
(vehicle_id, battery_id, start_cycle) exists precisely so a refitted pack adds
a new period rather than overwriting the old one - and one period may still be
open. This API refuses the delete instead.
"""

import math
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError

from database import get_db_connection

battery_packs_bp = Blueprint(
    "battery_packs",
    __name__,
    url_prefix="/api/battery-packs"
)


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Free-text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "chemistry": 50,
}

# Must match chk_battery_health in schema.sql exactly, including the casing.
HEALTH_STATUSES = ("Excellent", "Good", "Fair", "Poor", "Replace")

# capacity_wh is DECIMAL(10,2): 10 total digits, 2 of them after the point.
MAX_CAPACITY_VALUE = Decimal("99999999.99")
DECIMAL_PLACES = 2

# cycle_count is a signed INT; chk_battery_cycles allows zero.
MAX_CYCLE_COUNT = 2147483647
CYCLE_COUNT_MESSAGE = "cycle_count must be an integer greater than or equal to 0"

# Every field a client may send. battery_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | {"capacity_wh", "health_status", "cycle_count"}

# Value used when POST omits cycle_count, matching the column DEFAULT.
DEFAULT_CYCLE_COUNT = 0

# Columns selected by every read, in a fixed order.
BATTERY_COLUMNS = (
    "battery_id, chemistry, capacity_wh, health_status, cycle_count"
)

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Battery pack %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every capacity read back
    from MySQL passes through here.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def serialize_battery(row):
    """Convert one database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "battery_id": row["battery_id"],
        "chemistry": row["chemistry"],
        "capacity_wh": decimal_to_number(row["capacity_wh"]),
        "health_status": row["health_status"],
        "cycle_count": row["cycle_count"],
    }


def build_battery_payload(battery_id, cleaned):
    """Build the response body for a freshly created or updated battery."""
    return {
        "battery_id": battery_id,
        "chemistry": cleaned["chemistry"],
        "capacity_wh": decimal_to_number(cleaned["capacity_wh"]),
        "health_status": cleaned["health_status"],
        "cycle_count": cleaned["cycle_count"],
    }


def parse_capacity_wh(value, errors):
    """Validate capacity_wh and return it as a Decimal, or None.

    Records its own problem in `errors` and returns None when the value is
    unusable, so the caller can keep collecting the remaining errors.
    """
    field = "capacity_wh"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise be accepted
    # and stored as a capacity of 1 Wh.
    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    # Rejects strings such as "10500" as well as lists, dicts and null.
    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        # Decimal(value) on a float would introduce binary rounding noise and
        # make the decimal-place check meaningless.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    # exponent -3 means three digits after the point, and so on.
    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_CAPACITY_VALUE:
        errors[field] = f"{field} must not exceed {MAX_CAPACITY_VALUE}"
        return None

    # chk_battery_capacity is strictly greater than zero, so 0 is rejected.
    if parsed <= 0:
        errors[field] = f"{field} must be greater than 0"
        return None

    return parsed


def parse_cycle_count(payload, errors, required):
    """Validate cycle_count and return an int, or None.

    Absence and an explicit null are treated differently:

      * key missing on POST  -> default to 0, matching the column DEFAULT
      * key missing on PUT   -> error, since PUT is a full replacement
      * key present but null -> always an error; an explicitly bad value is
        never quietly replaced with the default

    That distinction is why this helper takes the whole payload rather than
    payload.get("cycle_count"), which cannot tell the two cases apart.
    """
    field = "cycle_count"

    if field not in payload:
        if required:
            errors[field] = f"{field} is required"
            return None
        return DEFAULT_CYCLE_COUNT

    value = payload[field]

    if value is None:
        errors[field] = CYCLE_COUNT_MESSAGE
        return None

    # bool is a subclass of int, so True would otherwise be stored as 1 cycle.
    if isinstance(value, bool):
        errors[field] = CYCLE_COUNT_MESSAGE
        return None

    # A genuine JSON integer only: 12.0 arrives as a float and is rejected,
    # as are strings, lists and dicts.
    if not isinstance(value, int):
        errors[field] = CYCLE_COUNT_MESSAGE
        return None

    # chk_battery_cycles allows zero, unlike every other numeric CHECK here.
    if value < 0:
        errors[field] = CYCLE_COUNT_MESSAGE
        return None

    if value > MAX_CYCLE_COUNT:
        errors[field] = f"{field} must not exceed {MAX_CYCLE_COUNT}"
        return None

    return value


def parse_health_status(value, errors):
    """Validate health_status against the CHECK list, case-sensitively."""
    field = "health_status"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    if not isinstance(value, str):
        errors[field] = f"{field} must be a string"
        return None

    trimmed = value.strip()
    if not trimmed:
        errors[field] = f"{field} must not be empty"
        return None

    if trimmed not in HEALTH_STATUSES:
        # Case is significant: 'good' is rejected rather than corrected, so a
        # client typo never turns into a silently different value.
        errors[field] = f"{field} must be one of: {', '.join(HEALTH_STATUSES)}"
        return None

    return trimmed


def validate_battery_payload(payload, require_cycle_count):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `require_cycle_count` is False for POST, where an omitted cycle_count
    becomes 0, and True for PUT, which replaces the whole record and therefore
    demands every field. Everything else is validated identically.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Free-text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- capacity_wh: numeric, finite, > 0, <= 99999999.99, 2 decimals. ---
    capacity_wh = parse_capacity_wh(payload.get("capacity_wh"), errors)
    if capacity_wh is not None:
        cleaned["capacity_wh"] = capacity_wh

    # --- health_status: exact match against the CHECK list. ---
    health_status = parse_health_status(payload.get("health_status"), errors)
    if health_status is not None:
        cleaned["health_status"] = health_status

    # --- cycle_count: genuine integer >= 0, optional on POST only. ---
    cycle_count = parse_cycle_count(payload, errors, require_cycle_count)
    if cycle_count is not None:
        cleaned["cycle_count"] = cycle_count

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_battery(cursor, battery_id):
    """Return one battery row, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {BATTERY_COLUMNS} FROM battery_pack WHERE battery_id = %s",
        (battery_id,)
    )
    return cursor.fetchone()


def count_vehicle_assignments(cursor, battery_id):
    """Count every vehicle_battery row for this battery.

    Both closed and currently open periods are counted - there is no
    end_cycle IS NULL filter - because a completed deployment is still history
    worth protecting.
    """
    cursor.execute(
        """
        SELECT COUNT(*) AS assignment_count
          FROM vehicle_battery
         WHERE battery_id = %s
        """,
        (battery_id,)
    )
    return int(cursor.fetchone()["assignment_count"])


def not_found_response():
    """Build the standard HTTP 404 body for a missing battery pack."""
    return jsonify({
        "success": False,
        "message": "Battery pack not found"
    }), 404


# ============================================================================
# ENDPOINT 1 - list all battery packs
# ============================================================================

@battery_packs_bp.route("", methods=["GET"])
def list_battery_packs():
    """GET /api/battery-packs - every pack, ordered by battery_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {BATTERY_COLUMNS} FROM battery_pack ORDER BY battery_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        batteries = [serialize_battery(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(batteries),
            "data": batteries
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one battery pack
# ============================================================================

@battery_packs_bp.route("/<int:battery_id>", methods=["GET"])
def get_battery_pack(battery_id):
    """GET /api/battery-packs/<id> - one pack, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_battery(cursor, battery_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_battery(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a battery pack
# ============================================================================

@battery_packs_bp.route("", methods=["POST"])
def create_battery_pack():
    """POST /api/battery-packs - validate, insert, return the new row.

    cycle_count is optional here and normalizes to 0 when omitted. The value
    is written explicitly rather than relying on the column DEFAULT, so the
    inserted row and the response body cannot drift apart.

    There is no duplicate check: the schema has no UNIQUE constraint, so two
    packs with identical specifications are valid records of two separate
    physical batteries.
    """
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_battery_payload(payload, require_cycle_count=False)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        # The Decimal is passed straight through as a parameter; the driver
        # renders it without any float round-trip.
        cursor.execute(
            """
            INSERT INTO battery_pack
                (chemistry, capacity_wh, health_status, cycle_count)
            VALUES (%s, %s, %s, %s)
            """,
            (
                cleaned["chemistry"],
                cleaned["capacity_wh"],
                cleaned["health_status"],
                cleaned["cycle_count"],
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Battery pack created successfully",
            "data": build_battery_payload(cursor.lastrowid, cleaned)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)
        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace a battery pack
# ============================================================================

@battery_packs_bp.route("/<int:battery_id>", methods=["PUT"])
def update_battery_pack(battery_id):
    """PUT /api/battery-packs/<id> - full replacement of the four columns.

    Every field is required here, cycle_count included: a full replacement
    that silently reset the cycle count to 0 would quietly discard a pack's
    accumulated wear.

    Only the battery_pack row is touched. vehicle_battery assignment history
    is never read or modified.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_battery_payload(payload, require_cycle_count=True)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_battery(cursor, battery_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE battery_pack
               SET chemistry     = %s,
                   capacity_wh   = %s,
                   health_status = %s,
                   cycle_count   = %s
             WHERE battery_id = %s
            """,
            (
                cleaned["chemistry"],
                cleaned["capacity_wh"],
                cleaned["health_status"],
                cleaned["cycle_count"],
                battery_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Battery pack updated successfully",
            "data": build_battery_payload(battery_id, cleaned)
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - protected delete
# ============================================================================

@battery_packs_bp.route("/<int:battery_id>", methods=["DELETE"])
def delete_battery_pack(battery_id):
    """DELETE /api/battery-packs/<id> - only when no assignment history exists.

    fk_vb_battery cascades in the schema, which would silently destroy the
    record of which vehicle carried this pack and over which period - possibly
    including a cycle that is still open. This endpoint refuses instead, and
    reports how many assignment rows are in the way.

    On one connection inside one transaction:

        1. lock the battery row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count vehicle_battery rows, closed and open alike
        4. 409 with the count if non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT

    There is deliberately no force-delete option, and vehicle_battery rows are
    never removed by this API.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()

        # Be explicit rather than relying on the driver's default, so the
        # lock taken below is definitely held until commit or rollback.
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it underneath us.
        cursor.execute(
            "SELECT battery_id FROM battery_pack WHERE battery_id = %s FOR UPDATE",
            (battery_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        assignment_count = count_vehicle_assignments(cursor, battery_id)

        if assignment_count > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Battery pack cannot be deleted because it has "
                           "vehicle assignment history",
                "dependencies": {
                    "vehicle_assignments": assignment_count
                }
            }), 409

        cursor.execute(
            "DELETE FROM battery_pack WHERE battery_id = %s",
            (battery_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Battery pack deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch: fk_vb_battery uses ON DELETE CASCADE, so MySQL never
        # raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
