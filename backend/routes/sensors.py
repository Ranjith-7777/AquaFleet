"""
routes/sensors.py
-----------------
CRUD REST API for the `sensor` table.

    GET    /api/sensors             list every sensor
    GET    /api/sensors/<id>        fetch one sensor
    POST   /api/sensors             create a sensor
    PUT    /api/sensors/<id>        replace a sensor
    DELETE /api/sensors/<id>        delete a sensor, if no vehicle uses it

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, commit/rollback around
writes, cleanup in finally blocks, full error logging server-side and a
generic message to the client.

THREE THINGS DIFFER FROM THE EARLIER MODULES
--------------------------------------------
1. No duplicate handling. `sensor` has no UNIQUE constraint - the primary key
   is the only index - so two identical sensor rows are perfectly legal. There
   is deliberately no 409-on-duplicate branch here, because MySQL error 1062
   can never be raised by this table.

2. accuracy is DECIMAL(6,3), not DECIMAL(8,2). That means a maximum of 999.999
   and THREE decimal places, so the constants from vehicles.py and
   marine_zones.py do not carry over. Four of the six seeded sensors have
   three-decimal accuracies such as 0.005.

3. calibration_date is the project's first DATE column. It is parsed strictly,
   and because the value records a calibration that has already happened, a
   date after today is rejected.

PROTECTED DELETE
----------------
vehicle_sensor declares ON DELETE CASCADE, so MySQL would quietly erase the
mount_position and install_date rows recording where this instrument was
fitted, and would never raise error 1451. That installation history is worth
keeping, so this API refuses instead.
"""

import math
from datetime import date, datetime
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError

from database import get_db_connection

sensors_bp = Blueprint("sensors", __name__, url_prefix="/api/sensors")


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Free-text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "sensor_type": 80,
    "manufacturer": 100,
}

# accuracy is DECIMAL(6,3): 6 total digits, 3 of them after the point.
MAX_ACCURACY_VALUE = Decimal("999.999")
DECIMAL_PLACES = 3

# The one and only accepted calibration_date format.
DATE_FORMAT = "%Y-%m-%d"
DATE_FORMAT_MESSAGE = "calibration_date must be a valid date in YYYY-MM-DD format"

# Every field a client may send. sensor_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | {"calibration_date", "accuracy"}

# Columns selected by every read, in a fixed order.
SENSOR_COLUMNS = "sensor_id, sensor_type, manufacturer, calibration_date, accuracy"

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Sensor %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every accuracy read back
    from MySQL passes through here. float() is safe at this point because the
    value is already constrained to 6 digits with 3 decimal places.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def date_to_iso(value):
    """Render a DATE as YYYY-MM-DD.

    The driver returns datetime.date, which Flask would otherwise serialize as
    an RFC 1123 string like "Thu, 15 Jan 2026 00:00:00 GMT". isoformat() keeps
    the response identical to what the client sent.
    """
    if isinstance(value, date):
        return value.isoformat()
    return value


def serialize_sensor(row):
    """Convert one database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "sensor_id": row["sensor_id"],
        "sensor_type": row["sensor_type"],
        "manufacturer": row["manufacturer"],
        "calibration_date": date_to_iso(row["calibration_date"]),
        "accuracy": decimal_to_number(row["accuracy"]),
    }


def build_sensor_payload(sensor_id, cleaned):
    """Build the response body for a freshly created or updated sensor."""
    return {
        "sensor_id": sensor_id,
        "sensor_type": cleaned["sensor_type"],
        "manufacturer": cleaned["manufacturer"],
        "calibration_date": date_to_iso(cleaned["calibration_date"]),
        "accuracy": decimal_to_number(cleaned["accuracy"]),
    }


def parse_calibration_date(value, errors):
    """Validate calibration_date strictly and return a datetime.date, or None.

    Only the exact form YYYY-MM-DD is accepted. strptime alone is not quite
    strict enough - it would also swallow "2026-8-10" - so the parsed result is
    formatted back and compared against what was submitted. That round trip
    rejects single-digit months and days, while strptime itself rejects
    compact forms (20260810), timestamps (2026-08-10T12:00:00), zero dates
    and impossible calendar dates such as 2026-02-30.
    """
    field = "calibration_date"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    if not isinstance(value, str):
        errors[field] = f"{field} must be a string"
        return None

    trimmed = value.strip()
    if not trimmed:
        errors[field] = f"{field} must not be empty"
        return None

    try:
        parsed = datetime.strptime(trimmed, DATE_FORMAT).date()
    except ValueError:
        errors[field] = DATE_FORMAT_MESSAGE
        return None

    # Round trip: "2026-8-10" parses but does not format back identically.
    if parsed.strftime(DATE_FORMAT) != trimmed:
        errors[field] = DATE_FORMAT_MESSAGE
        return None

    # date.today() is read per request, never frozen at import time, so the
    # boundary moves with the server clock.
    if parsed > date.today():
        errors[field] = f"{field} cannot be in the future"
        return None

    return parsed


def parse_accuracy(value, errors):
    """Validate accuracy and return it as a Decimal, or None.

    Records its own problem in `errors` and returns None when the value is
    unusable, so the caller can keep collecting the remaining errors.
    """
    field = "accuracy"

    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise be accepted
    # and stored as an accuracy of 1.
    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    # Rejects strings such as "0.005" as well as lists, dicts and null.
    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        # Decimal(value) on a float would introduce binary rounding noise and
        # make the decimal-place check meaningless.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    # exponent -4 means four digits after the point, and so on. The column
    # holds three, so 0.0001 is rejected while 0.005 is fine.
    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    if abs(parsed) > MAX_ACCURACY_VALUE:
        errors[field] = f"{field} must not exceed {MAX_ACCURACY_VALUE}"
        return None

    # chk_sensor_accuracy is strictly greater than zero, so 0 is rejected.
    if parsed <= 0:
        errors[field] = f"{field} must be greater than 0"
        return None

    return parsed


def validate_sensor_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` holds trimmed text, a datetime.date and a Decimal accuracy
    ready to be used as SQL parameters. When `errors` is non-empty the caller
    must reject the request with HTTP 400. All problems are collected in one
    pass.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Free-text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- calibration_date: strict YYYY-MM-DD, today or earlier. ---
    calibration_date = parse_calibration_date(payload.get("calibration_date"), errors)
    if calibration_date is not None:
        cleaned["calibration_date"] = calibration_date

    # --- accuracy: numeric, finite, > 0, <= 999.999, at most 3 decimals. ---
    accuracy = parse_accuracy(payload.get("accuracy"), errors)
    if accuracy is not None:
        cleaned["accuracy"] = accuracy

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_sensor(cursor, sensor_id):
    """Return one sensor row, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {SENSOR_COLUMNS} FROM sensor WHERE sensor_id = %s",
        (sensor_id,)
    )
    return cursor.fetchone()


def count_vehicle_assignments(cursor, sensor_id):
    """Count the vehicle_sensor rows that point at this sensor."""
    cursor.execute(
        """
        SELECT COUNT(*) AS assignment_count
          FROM vehicle_sensor
         WHERE sensor_id = %s
        """,
        (sensor_id,)
    )
    return int(cursor.fetchone()["assignment_count"])


def not_found_response():
    """Build the standard HTTP 404 body for a missing sensor."""
    return jsonify({
        "success": False,
        "message": "Sensor not found"
    }), 404


# ============================================================================
# ENDPOINT 1 - list all sensors
# ============================================================================

@sensors_bp.route("", methods=["GET"])
def list_sensors():
    """GET /api/sensors - every sensor, ordered by sensor_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {SENSOR_COLUMNS} FROM sensor ORDER BY sensor_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        sensors = [serialize_sensor(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(sensors),
            "data": sensors
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one sensor
# ============================================================================

@sensors_bp.route("/<int:sensor_id>", methods=["GET"])
def get_sensor(sensor_id):
    """GET /api/sensors/<id> - one sensor, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_sensor(cursor, sensor_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_sensor(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create a sensor
# ============================================================================

@sensors_bp.route("", methods=["POST"])
def create_sensor():
    """POST /api/sensors - validate, insert, return the new row.

    There is no duplicate check: the schema has no UNIQUE constraint, so two
    sensors with identical type, manufacturer, date and accuracy are valid
    records of two separate physical instruments.
    """
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_sensor_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        # The Decimal and the date object are passed straight through as
        # parameters; the driver renders both without a float round-trip.
        cursor.execute(
            """
            INSERT INTO sensor (sensor_type, manufacturer, calibration_date, accuracy)
            VALUES (%s, %s, %s, %s)
            """,
            (
                cleaned["sensor_type"],
                cleaned["manufacturer"],
                cleaned["calibration_date"],
                cleaned["accuracy"],
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Sensor created successfully",
            "data": build_sensor_payload(cursor.lastrowid, cleaned)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)
        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace a sensor
# ============================================================================

@sensors_bp.route("/<int:sensor_id>", methods=["PUT"])
def update_sensor(sensor_id):
    """PUT /api/sensors/<id> - full replacement of the four columns.

    Only the sensor row is touched. vehicle_sensor assignments, including
    mount_position and install_date, are never read or modified here.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so all four fields are required, exactly
    # as they are for POST.
    cleaned, errors = validate_sensor_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_sensor(cursor, sensor_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE sensor
               SET sensor_type      = %s,
                   manufacturer     = %s,
                   calibration_date = %s,
                   accuracy         = %s
             WHERE sensor_id = %s
            """,
            (
                cleaned["sensor_type"],
                cleaned["manufacturer"],
                cleaned["calibration_date"],
                cleaned["accuracy"],
                sensor_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Sensor updated successfully",
            "data": build_sensor_payload(sensor_id, cleaned)
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - protected delete
# ============================================================================

@sensors_bp.route("/<int:sensor_id>", methods=["DELETE"])
def delete_sensor(sensor_id):
    """DELETE /api/sensors/<id> - only when no vehicle carries the sensor.

    fk_vs_sensor cascades in the schema, which would silently destroy the
    record of where this instrument was mounted and when it was installed.
    This endpoint refuses instead, and reports how many assignments are in
    the way.

    On one connection inside one transaction:

        1. lock the sensor row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count vehicle_sensor rows
        4. 409 with the count if non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT

    There is deliberately no force-delete option, and vehicle_sensor rows are
    never removed by this API.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()

        # Be explicit rather than relying on the driver's default, so the
        # lock taken below is definitely held until commit or rollback.
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it underneath us.
        cursor.execute(
            "SELECT sensor_id FROM sensor WHERE sensor_id = %s FOR UPDATE",
            (sensor_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        assignment_count = count_vehicle_assignments(cursor, sensor_id)

        if assignment_count > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Sensor cannot be deleted because it is assigned "
                           "to one or more vehicles",
                "dependencies": {
                    "vehicle_assignments": assignment_count
                }
            }), 409

        cursor.execute(
            "DELETE FROM sensor WHERE sensor_id = %s",
            (sensor_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Sensor deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch: fk_vs_sensor uses ON DELETE CASCADE, so MySQL never
        # raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
