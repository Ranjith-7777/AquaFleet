@offshore_assets_bp.route("/<int:asset_id>", methods=["PUT"])
def update_offshore_asset(asset_id):
    """PUT /api/offshore-assets/<id> - full replacement of the four columns.

    Only the offshore_asset row is touched. inspection_task rows, including
    their findings, are never read or modified here.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so all four fields are required, exactly
    # as they are for POST.
    cleaned, errors = validate_asset_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        # Confirm the row exists before attempting the UPDATE, so a missing
        # id gives a clear 404 instead of a silent "0 rows affected".
        if fetch_asset(cursor, asset_id) is None:
            return not_found_response()

        cursor.execute(
            """
            UPDATE offshore_asset
               SET asset_name = %s,
                   asset_type = %s,
                   latitude   = %s,
                   longitude  = %s
             WHERE asset_id = %s
            """,
            (
                cleaned["asset_name"],
                cleaned["asset_type"],
                cleaned["latitude"],
                cleaned["longitude"],
                asset_id,
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Offshore asset updated successfully",
            "data": build_asset_payload(asset_id, cleaned)
        }), 200

    except MySQLError as err:
        safe_rollback(connection)

        # Renaming an asset to a name another asset already uses.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 5 - protected delete
# ============================================================================

@offshore_assets_bp.route("/<int:asset_id>", methods=["DELETE"])
def delete_offshore_asset(asset_id):
    """DELETE /api/offshore-assets/<id> - only when nothing inspects it.

    fk_inspection_asset is ON DELETE RESTRICT, so unlike the cascade-protected
    resources elsewhere in this API, MySQL enforces the rule itself. This
    endpoint layers a pre-count on top so the client learns HOW MANY tasks are
    in the way, and keeps the 1451 handler as a genuine safety net.

    On one connection inside one transaction:

        1. lock the asset row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count inspection_task rows, whatever their status
        4. 409 with the count if non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT
        6. if MySQL still refuses with 1451, report the same 409

    inspection_task rows are never removed by this API.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()

        # Be explicit rather than relying on the driver's default, so the
        # lock taken below is definitely held until commit or rollback.
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it underneath us.
        cursor.execute(
            "SELECT asset_id FROM offshore_asset WHERE asset_id = %s FOR UPDATE",
            (asset_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        task_count = count_inspection_tasks(cursor, asset_id)

        if task_count > 0:
            # Release the lock without issuing any DELETE at all.
            connection.rollback()
            return referenced_response(task_count)

        cursor.execute(
            "DELETE FROM offshore_asset WHERE asset_id = %s",
            (asset_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Offshore asset deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)

        # Safety net. The pre-count above should already have caught this, but
        # a task inserted between the count and the DELETE would land here.
        # Re-count on a fresh connection so the client still gets a number;
        # recount_after_restrict returns None if even that fails, and the
        # response then omits the count rather than inventing one.
        if err.errno == errorcode.ER_ROW_IS_REFERENCED_2:
            current_app.logger.warning(
                "Offshore asset %s delete refused by MySQL 1451 after the "
                "pre-count reported zero dependencies", asset_id
            )
            return restrict_fallback_response(recount_after_restrict(asset_id))

        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)


def recount_after_restrict(asset_id):
    """Re-read the dependency count after MySQL refused a delete with 1451.

    The transaction that hit the error has been rolled back, so this opens its
    own short-lived connection.

    Returns the count, or None when the recount itself fails. None means "the
    delete was refused but the number is unknown" - the caller then omits the
    dependencies object entirely rather than reporting a made-up figure.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        return count_inspection_tasks(cursor, asset_id)
    except MySQLError as err:
        current_app.logger.error(
            "Offshore asset %s dependency recount failed after MySQL 1451: %s",
            asset_id, err, exc_info=True
        )
        return None
    finally:
        close_resources(cursor, connection)
