# ENDPOINT 3 - create an asset
# ============================================================================

@offshore_assets_bp.route("", methods=["POST"])
def create_offshore_asset():
    """POST /api/offshore-assets - validate, insert, return the new row."""
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_asset_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor()

        # The Decimals are passed straight through as parameters; the driver
        # renders them without any float round-trip.
        cursor.execute(
            """
            INSERT INTO offshore_asset (asset_name, asset_type, latitude, longitude)
            VALUES (%s, %s, %s, %s)
            """,
            (
                cleaned["asset_name"],
                cleaned["asset_type"],
                cleaned["latitude"],
                cleaned["longitude"],
            )
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Offshore asset created successfully",
            "data": build_asset_payload(cursor.lastrowid, cleaned)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)

        # Letting MySQL detect the duplicate - rather than doing a SELECT
        # first - is what makes this correct when two requests race. The
        # collation is case-insensitive, so names differing only by case
        # collide too.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_name_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


