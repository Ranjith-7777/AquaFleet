"""
routes/offshore_assets.py
-------------------------
CRUD REST API for the `offshore_asset` table.

    GET    /api/offshore-assets             list every asset
    GET    /api/offshore-assets/<id>        fetch one asset
    POST   /api/offshore-assets             create an asset
    PUT    /api/offshore-assets/<id>        replace an asset
    DELETE /api/offshore-assets/<id>        delete an asset with no inspections

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, commit/rollback around
writes, cleanup in finally blocks, full error logging server-side and a
generic message to the client.

TWO THINGS DIFFER FROM THE EARLIER MODULES
------------------------------------------
1. Signed, inclusive coordinate ranges. latitude and longitude are
   DECIMAL(9,6) - a fourth distinct precision in this project, with SIX
   decimal places - and they are the first numeric fields that legitimately
   accept negative values. Latitude spans -90 to 90 and longitude -180 to 180,
   both inclusive, so each column needs its own explicit bounds rather than a
   shared magnitude check.

2. The database already protects the child rows. fk_inspection_asset is
   ON DELETE RESTRICT, not CASCADE, so MySQL refuses the delete itself with
   error 1451. Unlike vehicles, sensors, batteries and operators, that error
   is reachable here and is kept as a genuine safety net.

DELETE STRATEGY
---------------
The endpoint counts inspection_task rows inside a locked transaction so it can
report exactly how many are in the way, then falls back to catching 1451 if
MySQL refuses anyway. The pre-count gives the informative message; the 1451
handler guarantees correctness even if a task is inserted after the count.
All rows are counted regardless of status - a Cancelled task still blocks -
so the API and the schema's RESTRICT rule never disagree.
"""

import math
from decimal import Decimal, InvalidOperation

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

offshore_assets_bp = Blueprint(
    "offshore_assets",
    __name__,
    url_prefix="/api/offshore-assets"
)


# ============================================================================
# Validation rules for the editable columns
# ============================================================================

# Free-text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "asset_name": 120,
    "asset_type": 80,
}

# Coordinate columns, each with its own inclusive bounds from the CHECK
# constraints. Note the bounds are signed: a southern or western asset has a
# negative coordinate, and -90 / -180 are themselves valid.
COORDINATE_FIELDS = {
    "latitude": (Decimal("-90"), Decimal("90")),
    "longitude": (Decimal("-180"), Decimal("180")),
}

# latitude and longitude are DECIMAL(9,6): 9 total digits, 6 after the point.
DECIMAL_PLACES = 6

# Every field a client may send. asset_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | set(COORDINATE_FIELDS)

# Columns selected by every read, in a fixed order.
ASSET_COLUMNS = "asset_id, asset_name, asset_type, latitude, longitude"

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Offshore asset %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def decimal_to_number(value):
    """Turn a Decimal into a plain JSON number.

    jsonify() cannot serialize decimal.Decimal, so every coordinate read back
    from MySQL passes through here. float() is safe at this point because the
    value is already constrained to 9 digits with 6 decimal places, which a
    double represents to well beyond centimetre precision.
    """
    if isinstance(value, Decimal):
        return float(value)
    return value


def serialize_asset(row):
    """Convert one database row into a JSON-safe dict."""
    if row is None:
        return None
    return {
        "asset_id": row["asset_id"],
        "asset_name": row["asset_name"],
        "asset_type": row["asset_type"],
        "latitude": decimal_to_number(row["latitude"]),
        "longitude": decimal_to_number(row["longitude"]),
    }


def build_asset_payload(asset_id, cleaned):
    """Build the response body for a freshly created or updated asset."""
    return {
        "asset_id": asset_id,
        "asset_name": cleaned["asset_name"],
        "asset_type": cleaned["asset_type"],
        "latitude": decimal_to_number(cleaned["latitude"]),
        "longitude": decimal_to_number(cleaned["longitude"]),
    }


def parse_coordinate(field, value, minimum, maximum, errors):
    """Validate one coordinate and return it as a Decimal, or None.

    Records its own problem in `errors` and returns None when the value is
    unusable, so the caller can keep collecting the remaining errors.
    """
    if value is None:
        errors[field] = f"{field} is required"
        return None

    # bool is a subclass of int in Python, so True would otherwise be accepted
    # and stored as a coordinate of 1.
    if isinstance(value, bool):
        errors[field] = f"{field} must be a number"
        return None

    # Rejects strings such as "19.4512" as well as lists, dicts and null.
    if not isinstance(value, (int, float)):
        errors[field] = f"{field} must be a number"
        return None

    # Python's JSON parser accepts NaN, Infinity and -Infinity even though they
    # are not valid JSON, so they have to be filtered out explicitly.
    if isinstance(value, float) and not math.isfinite(value):
        errors[field] = f"{field} must be a finite number"
        return None

    try:
        # Decimal(str(value)) keeps the digits the client actually sent.
        # Decimal(value) on a float would introduce binary rounding noise and
        # make the decimal-place check meaningless.
        parsed = Decimal(str(value))
    except (InvalidOperation, ValueError):
        errors[field] = f"{field} must be a number"
        return None

    # exponent -7 means seven digits after the point, and so on.
    if -parsed.as_tuple().exponent > DECIMAL_PLACES:
        errors[field] = f"{field} must have at most {DECIMAL_PLACES} decimal places"
        return None

    # Inclusive on both ends, matching BETWEEN in the CHECK constraints. A
    # magnitude test would be wrong here: the range is signed, not symmetric
    # around a single ceiling shared by both columns.
    if parsed < minimum or parsed > maximum:
        errors[field] = f"{field} must be between {minimum} and {maximum}"
        return None

    return parsed


def validate_asset_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` holds trimmed text and Decimal coordinates ready to be
    used as SQL parameters. When `errors` is non-empty the caller must reject
    the request with HTTP 400. All problems are collected in one pass.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Free-text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- Coordinates: numeric, finite, in range, at most six decimals. ---
    for field, (minimum, maximum) in COORDINATE_FIELDS.items():
        coordinate = parse_coordinate(
            field, payload.get(field), minimum, maximum, errors
        )
        if coordinate is not None:
            cleaned[field] = coordinate

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_asset(cursor, asset_id):
    """Return one asset row, or None when the id does not exist.

    Takes an existing dictionary cursor so the caller can reuse the same
    connection for the surrounding read or write.
    """
    cursor.execute(
        f"SELECT {ASSET_COLUMNS} FROM offshore_asset WHERE asset_id = %s",
        (asset_id,)
    )
    return cursor.fetchone()


def count_inspection_tasks(cursor, asset_id):
    """Count every inspection_task row that targets this asset.

    All rows count, whatever their status. A Cancelled task still blocks
    deletion, because fk_inspection_asset RESTRICTs on row existence alone -
    ignoring cancelled rows would let the API promise a delete that MySQL
    would then refuse with error 1451.
    """
    cursor.execute(
        """
        SELECT COUNT(*) AS task_count
          FROM inspection_task
         WHERE asset_id = %s
        """,
        (asset_id,)
    )
    return int(cursor.fetchone()["task_count"])


def not_found_response():
    """Build the standard HTTP 404 body for a missing asset."""
    return jsonify({
        "success": False,
        "message": "Offshore asset not found"
    }), 404


def duplicate_name_response():
    """Build the standard HTTP 409 body for a UNIQUE(asset_name) violation."""
    return jsonify({
        "success": False,
        "message": "An offshore asset with this name already exists"
    }), 409


def referenced_response(task_count):
    """Build the standard HTTP 409 body for an asset with inspection history.

    Used on the normal path, where the pre-count inside the transaction gives
    a count we know to be accurate.
    """
    return jsonify({
        "success": False,
        "message": "Offshore asset cannot be deleted because it has "
                   "one or more inspection tasks",
        "dependencies": {
            "inspection_tasks": task_count
        }
    }), 409


def restrict_fallback_response(task_count):
    """Build the HTTP 409 body for the MySQL 1451 safety net.

    `task_count` is None when the recount could not be performed. In that case
    the response carries no `dependencies` object at all: the delete was
    definitely refused, but we do not know how many tasks are in the way, and
    a guessed number would be worse than no number.
    """
    body = {
        "success": False,
        "message": "Offshore asset cannot be deleted because it has "
                   "inspection history",
    }

    if task_count is not None:
        body["dependencies"] = {"inspection_tasks": task_count}

    return jsonify(body), 409


# ============================================================================
# ENDPOINT 1 - list all assets
# ============================================================================

@offshore_assets_bp.route("", methods=["GET"])
def list_offshore_assets():
    """GET /api/offshore-assets - every asset, ordered by asset_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute(
            f"SELECT {ASSET_COLUMNS} FROM offshore_asset ORDER BY asset_id"
        )
        rows = cursor.fetchall()

        # An empty table is a valid result, not an error: count 0, data [].
        assets = [serialize_asset(row) for row in rows]

        return jsonify({
            "success": True,
            "count": len(assets),
            "data": assets
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one asset
# ============================================================================

@offshore_assets_bp.route("/<int:asset_id>", methods=["GET"])
def get_offshore_asset(asset_id):
    """GET /api/offshore-assets/<id> - one asset, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        row = fetch_asset(cursor, asset_id)

        if row is None:
            return not_found_response()

        return jsonify({
            "success": True,
            "data": serialize_asset(row)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


