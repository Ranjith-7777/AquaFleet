# ENDPOINT 5 - protected delete
# ============================================================================

@operators_bp.route("/<int:operator_id>", methods=["DELETE"])
def delete_operator(operator_id):
    """DELETE /api/operators/<id> - only when no mission references them.

    mission_operator cascades in the schema, which would silently erase the
    staffing record of completed missions. This endpoint refuses instead.

    operator_contact is owned profile data, so it is NOT counted as a blocker;
    on a successful delete the schema's ON DELETE CASCADE removes those rows,
    and this endpoint never deletes them by hand.

    On one connection inside one transaction:

        1. lock the operator row with SELECT ... FOR UPDATE
        2. 404 if it does not exist
        3. count mission_operator rows
        4. 409 with the count if non-zero - no DELETE is sent
        5. otherwise DELETE and COMMIT

    There is deliberately no force-delete option.
    """
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        cursor.execute(
            "SELECT operator_id FROM `operator` WHERE operator_id = %s FOR UPDATE",
            (operator_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        cursor.execute(
            """
            SELECT COUNT(*) AS mission_assignments
              FROM mission_operator
             WHERE operator_id = %s
            """,
            (operator_id,)
        )
        mission_assignments = int(cursor.fetchone()["mission_assignments"])

        if mission_assignments > 0:
            # Release the lock without issuing any DELETE at all. Note that
            # contact numbers are deliberately not part of this decision.
            connection.rollback()
            return jsonify({
                "success": False,
                "message": "Operator cannot be deleted because they are "
                           "assigned to one or more missions",
                "dependencies": {
                    "mission_assignments": mission_assignments
                }
            }), 409

        # fk_contact_operator ON DELETE CASCADE clears operator_contact for us.
        cursor.execute(
            "DELETE FROM `operator` WHERE operator_id = %s",
            (operator_id,)
        )
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Operator deleted successfully"
        }), 200

    except MySQLError as err:
        safe_rollback(connection)
        # No 1451 branch: both child foreign keys cascade, so MySQL never
        # raises it. The guard above is the only protection.
        return db_failure(err, "delete")

    finally:
        close_resources(cursor, connection)
