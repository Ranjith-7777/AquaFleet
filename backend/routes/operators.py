"""
routes/operators.py
-------------------
Combined CRUD REST API for the `operator` table and its multivalued
`operator_contact` records.

    GET    /api/operators             list every operator with contacts
    GET    /api/operators/<id>        fetch one operator with contacts
    POST   /api/operators             create an operator and its contacts
    PUT    /api/operators/<id>        replace an operator and its whole contact list
    DELETE /api/operators/<id>        delete an operator with no mission history

This module follows the same conventions as the other route modules:
parameterized SQL, dictionary cursors for reads, cleanup in finally blocks,
full error logging server-side and a generic message to the client.

`operator` is always written with backticks in SQL, since OPERATOR reads as
SQL terminology.

TWO THINGS DIFFER FROM THE EARLIER MODULES
------------------------------------------
1. Multi-table writes. An operator and its contact numbers are one logical
   record, so POST and PUT wrap both tables in a single transaction and commit
   only once every statement has succeeded. A partial operator - saved details
   with missing phone numbers, or the reverse - is never visible.

2. Asymmetric delete protection. Both child tables cascade in the schema, but
   they are not the same kind of data:

     * operator_contact is owned profile data. It is the multivalued contact_no
       attribute decomposed for 1NF, so letting it cascade loses nothing.
     * mission_operator is operational history. It records who crewed which
       mission, with duty_role and shift, and must never be destroyed as a
       side effect of removing a person.

   So deletion is blocked only by mission assignments. Contacts never block it.
"""

from flask import Blueprint, current_app, jsonify, request
from mysql.connector import Error as MySQLError
from mysql.connector import errorcode

from database import get_db_connection

operators_bp = Blueprint("operators", __name__, url_prefix="/api/operators")


# ============================================================================
# Validation rules
# ============================================================================

# Free-text columns and the maximum length allowed by the schema.
TEXT_FIELDS = {
    "first_name": 60,
    "last_name": 60,
    "role": 80,
    "certification_level": 50,
}

EMAIL_MAX_LENGTH = 120

# operator_contact.contact_no is VARCHAR(20).
CONTACT_MAX_LENGTH = 20

# Digit counts either side of the ITU E.164 range, once separators are ignored.
CONTACT_MIN_DIGITS = 7
CONTACT_MAX_DIGITS = 15

# Characters permitted after the leading '+'.
CONTACT_ALLOWED_CHARS = set("0123456789 -")

# Every field a client may send. operator_id is generated by MySQL.
ALLOWED_FIELDS = set(TEXT_FIELDS) | {"email", "contact_numbers"}

# Columns selected by every operator read, in a fixed order.
OPERATOR_COLUMNS = (
    "operator_id, first_name, last_name, `role`, certification_level, email"
)

CONTACT_FORMAT_MESSAGE = (
    "contact number must begin with + and contain only digits, spaces or hyphens"
)

# Message reused for any unexpected driver failure.
DB_ERROR_MESSAGE = "A database error occurred"


# ============================================================================
# Small reusable helpers
# ============================================================================

def close_resources(cursor, connection):
    """Release the cursor and the connection, ignoring anything already closed.

    Called from a finally block, so it must never raise - otherwise it would
    mask the original error that sent us there.
    """
    if cursor is not None:
        try:
            cursor.close()
        except MySQLError:
            pass
    if connection is not None:
        try:
            if connection.is_connected():
                connection.close()
        except MySQLError:
            pass


def safe_rollback(connection):
    """Roll back without letting a secondary failure hide the original error."""
    if connection is None:
        return
    try:
        connection.rollback()
    except MySQLError:
        pass


def db_failure(err, action):
    """Log a driver error in full and build the safe 500 response."""
    current_app.logger.error("Operator %s failed: %s", action, err, exc_info=True)
    return jsonify({
        "success": False,
        "message": DB_ERROR_MESSAGE
    }), 500


def serialize_operator(row, contact_numbers):
    """Build the combined operator representation."""
    return {
        "operator_id": row["operator_id"],
        "first_name": row["first_name"],
        "last_name": row["last_name"],
        "role": row["role"],
        "certification_level": row["certification_level"],
        "email": row["email"],
        # Always an array, even when the operator has no contacts on file.
        "contact_numbers": contact_numbers,
    }


def is_valid_email(value):
    """Practical email check - deliberately not full RFC 5322.

    Requires exactly one '@', a non-empty local part, a non-empty domain
    containing at least one dot, and no whitespace anywhere. MySQL handles
    uniqueness (case-insensitively, via the utf8mb4_unicode_ci collation on
    uq_operator_email), so this only screens out obvious nonsense.
    """
    if any(character.isspace() for character in value):
        return False

    if value.count("@") != 1:
        return False

    local_part, domain = value.split("@")

    if not local_part or not domain:
        return False

    # A dot is required, but not as the first or last character of the domain,
    # and the domain must have something on both sides of it.
    if "." not in domain:
        return False
    if domain.startswith(".") or domain.endswith("."):
        return False
    if ".." in domain:
        return False

    return True


def validate_contact_number(value):
    """Return (normalized, error) for a single contact number.

    `normalized` is the trimmed string exactly as it will be stored - hyphens
    and spaces are preserved rather than stripped, so the display format the
    client sent survives the round trip.
    """
    if not isinstance(value, str):
        return None, "contact number must be a string"

    trimmed = value.strip()

    if not trimmed:
        return None, "contact number must not be empty"

    if len(trimmed) > CONTACT_MAX_LENGTH:
        return None, f"contact number must be at most {CONTACT_MAX_LENGTH} characters"

    if not trimmed.startswith("+"):
        return None, CONTACT_FORMAT_MESSAGE

    body = trimmed[1:]

    # Rejects letters, parentheses, dots and every other symbol.
    if any(character not in CONTACT_ALLOWED_CHARS for character in body):
        return None, CONTACT_FORMAT_MESSAGE

    digits = [character for character in body if character.isdigit()]

    if len(digits) < CONTACT_MIN_DIGITS or len(digits) > CONTACT_MAX_DIGITS:
        return None, (
            f"contact number must contain between {CONTACT_MIN_DIGITS} and "
            f"{CONTACT_MAX_DIGITS} digits"
        )

    return trimmed, None


def validate_contact_numbers(value, errors):
    """Validate the contact_numbers array and return the normalized list.

    Problems are reported per index as contact_numbers[0], contact_numbers[1]
    and so on, so the client can see exactly which entry is wrong.
    """
    if value is None:
        errors["contact_numbers"] = "at least one contact number is required"
        return []

    # A string is iterable, so it has to be excluded explicitly or "abc" would
    # be read as three separate entries.
    if not isinstance(value, list):
        errors["contact_numbers"] = "contact_numbers must be an array"
        return []

    if not value:
        errors["contact_numbers"] = "at least one contact number is required"
        return []

    normalized_numbers = []
    seen = set()

    for index, item in enumerate(value):
        normalized, error = validate_contact_number(item)

        if error is not None:
            errors[f"contact_numbers[{index}]"] = error
            continue

        # Duplicate detection uses the final trimmed string, matching the
        # composite primary key (operator_id, contact_no). Global uniqueness is
        # deliberately NOT enforced - two operators may share a number.
        if normalized in seen:
            errors[f"contact_numbers[{index}]"] = "duplicate contact number"
            continue

        seen.add(normalized)
        normalized_numbers.append(normalized)

    return normalized_numbers


def validate_operator_payload(payload):
    """Check a POST/PUT body and return (cleaned_values, errors).

    `cleaned_values` holds trimmed text plus a normalized "contact_numbers"
    list. When `errors` is non-empty the caller must reject the request with
    HTTP 400. All problems are collected in one pass.
    """
    errors = {}
    cleaned = {}

    # --- The body itself must be a JSON object, not a list or a scalar. ---
    if not isinstance(payload, dict):
        return {}, {"body": "Request body must be a JSON object"}

    # --- Reject unknown keys, which are usually spelling mistakes. ---
    for key in payload:
        if key not in ALLOWED_FIELDS:
            errors[key] = f"{key} is not a recognised field"

    # --- Free-text fields: required, non-blank string, length-limited. ---
    for field, max_length in TEXT_FIELDS.items():
        value = payload.get(field)

        if value is None:
            errors[field] = f"{field} is required"
            continue

        if not isinstance(value, str):
            errors[field] = f"{field} must be a string"
            continue

        trimmed = value.strip()
        if not trimmed:
            errors[field] = f"{field} must not be empty"
            continue

        if len(trimmed) > max_length:
            errors[field] = f"{field} must be at most {max_length} characters"
            continue

        cleaned[field] = trimmed

    # --- email: trimmed, length-limited, practical structure check. ---
    email = payload.get("email")

    if email is None:
        errors["email"] = "email is required"
    elif not isinstance(email, str):
        errors["email"] = "email must be a string"
    else:
        # Trimmed but never case-folded: the stored value keeps whatever the
        # client typed, and MySQL's case-insensitive collation still prevents
        # two operators differing only by case.
        trimmed_email = email.strip()

        if not trimmed_email:
            errors["email"] = "email must not be empty"
        elif len(trimmed_email) > EMAIL_MAX_LENGTH:
            errors["email"] = f"email must be at most {EMAIL_MAX_LENGTH} characters"
        elif not is_valid_email(trimmed_email):
            errors["email"] = "email must be a valid email address"
        else:
            cleaned["email"] = trimmed_email

    # --- contact_numbers: non-empty array of well-formed numbers. ---
    contact_numbers = validate_contact_numbers(payload.get("contact_numbers"), errors)
    cleaned["contact_numbers"] = contact_numbers

    return cleaned, errors


def validation_response(errors):
    """Build the standard HTTP 400 body for a failed validation."""
    return jsonify({
        "success": False,
        "message": "Validation failed",
        "errors": errors
    }), 400


def fetch_operator_row(cursor, operator_id):
    """Return one operator row, or None when the id does not exist."""
    cursor.execute(
        f"SELECT {OPERATOR_COLUMNS} FROM `operator` WHERE operator_id = %s",
        (operator_id,)
    )
    return cursor.fetchone()


def fetch_contact_numbers(cursor, operator_id):
    """Return one operator's contact numbers, ordered consistently."""
    cursor.execute(
        """
        SELECT contact_no
          FROM operator_contact
         WHERE operator_id = %s
         ORDER BY contact_no
        """,
        (operator_id,)
    )
    return [row["contact_no"] for row in cursor.fetchall()]


def fetch_contacts_for_ids(cursor, operator_ids):
    """Return {operator_id: [contact_no, ...]} for many operators at once.

    One query covers the whole list, so listing N operators costs 2 queries
    rather than N + 1. The placeholder string is built from the *number* of
    ids, never from their values, so this stays fully parameterized.
    """
    if not operator_ids:
        return {}

    placeholders = ", ".join(["%s"] * len(operator_ids))
    cursor.execute(
        f"""
        SELECT operator_id, contact_no
          FROM operator_contact
         WHERE operator_id IN ({placeholders})
         ORDER BY operator_id, contact_no
        """,
        tuple(operator_ids)
    )

    grouped = {}
    for row in cursor.fetchall():
        grouped.setdefault(row["operator_id"], []).append(row["contact_no"])
    return grouped


def insert_contact_numbers(cursor, operator_id, contact_numbers):
    """Insert every contact number for one operator."""
    if not contact_numbers:
        return

    cursor.executemany(
        "INSERT INTO operator_contact (operator_id, contact_no) VALUES (%s, %s)",
        [(operator_id, number) for number in contact_numbers]
    )


def build_operator_payload(operator_id, cleaned):
    """Build the response body for a freshly created or updated operator."""
    return {
        "operator_id": operator_id,
        "first_name": cleaned["first_name"],
        "last_name": cleaned["last_name"],
        "role": cleaned["role"],
        "certification_level": cleaned["certification_level"],
        "email": cleaned["email"],
        # Sorted so the response matches what a later GET will return.
        "contact_numbers": sorted(cleaned["contact_numbers"]),
    }


def not_found_response():
    """Build the standard HTTP 404 body for a missing operator."""
    return jsonify({
        "success": False,
        "message": "Operator not found"
    }), 404


def duplicate_email_response():
    """Build the standard HTTP 409 body for a UNIQUE(email) violation."""
    return jsonify({
        "success": False,
        "message": "An operator with this email already exists"
    }), 409


# ============================================================================
# ENDPOINT 1 - list all operators
# ============================================================================

@operators_bp.route("", methods=["GET"])
def list_operators():
    """GET /api/operators - every operator with contacts, by operator_id."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        cursor.execute(
            f"SELECT {OPERATOR_COLUMNS} FROM `operator` ORDER BY operator_id"
        )
        rows = cursor.fetchall()

        # Second and final query: all contacts for all of those operators.
        contacts_by_operator = fetch_contacts_for_ids(
            cursor, [row["operator_id"] for row in rows]
        )

        # .get(..., []) means an operator with no contact rows still returns an
        # empty array rather than being dropped, which is what a LEFT JOIN
        # would give and keeps legacy rows visible.
        operators = [
            serialize_operator(row, contacts_by_operator.get(row["operator_id"], []))
            for row in rows
        ]

        return jsonify({
            "success": True,
            "count": len(operators),
            "data": operators
        }), 200

    except MySQLError as err:
        return db_failure(err, "list")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 2 - fetch one operator
# ============================================================================

@operators_bp.route("/<int:operator_id>", methods=["GET"])
def get_operator(operator_id):
    """GET /api/operators/<id> - one operator with contacts, or 404."""
    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)

        row = fetch_operator_row(cursor, operator_id)
        if row is None:
            return not_found_response()

        contact_numbers = fetch_contact_numbers(cursor, operator_id)

        return jsonify({
            "success": True,
            "data": serialize_operator(row, contact_numbers)
        }), 200

    except MySQLError as err:
        return db_failure(err, "fetch")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 3 - create an operator with contacts
# ============================================================================

@operators_bp.route("", methods=["POST"])
def create_operator():
    """POST /api/operators - insert the operator and its contacts atomically.

    Both tables are written inside one transaction. The commit happens only
    after the operator row and every contact row has been inserted, so a
    failure at any point leaves nothing behind.
    """
    # silent=True makes Flask return None for a malformed or missing body
    # instead of raising its own 400 HTML error page.
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    cleaned, errors = validate_operator_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        cursor.execute(
            """
            INSERT INTO `operator`
                (first_name, last_name, `role`, certification_level, email)
            VALUES (%s, %s, %s, %s, %s)
            """,
            (
                cleaned["first_name"],
                cleaned["last_name"],
                cleaned["role"],
                cleaned["certification_level"],
                cleaned["email"],
            )
        )

        new_id = cursor.lastrowid
        insert_contact_numbers(cursor, new_id, cleaned["contact_numbers"])

        # Only now is the whole record durable.
        connection.commit()

        return jsonify({
            "success": True,
            "message": "Operator created successfully",
            "data": build_operator_payload(new_id, cleaned)
        }), 201

    except MySQLError as err:
        safe_rollback(connection)

        # Letting MySQL detect the duplicate - rather than doing a SELECT
        # first - is what makes this correct when two requests race.
        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_email_response()

        return db_failure(err, "create")

    finally:
        close_resources(cursor, connection)


# ============================================================================
# ENDPOINT 4 - replace an operator and its whole contact list
# ============================================================================

@operators_bp.route("/<int:operator_id>", methods=["PUT"])
def update_operator(operator_id):
    """PUT /api/operators/<id> - full replacement of details and contacts.

    The contact list is replaced wholesale: the existing rows are deleted and
    the validated list is inserted in their place. Everything runs in one
    transaction, so a failure anywhere leaves the original operator AND the
    original contact numbers exactly as they were.

    mission_operator is never read or written here.
    """
    payload = request.get_json(silent=True)

    if payload is None:
        return validation_response({"body": "Request body must be a JSON object"})

    # PUT replaces the whole record, so every field is required, including a
    # non-empty contact_numbers array.
    cleaned, errors = validate_operator_payload(payload)
    if errors:
        return validation_response(errors)

    connection = None
    cursor = None

    try:
        connection = get_db_connection()
        connection.autocommit = False
        cursor = connection.cursor(dictionary=True)
        connection.start_transaction()

        # FOR UPDATE holds the row until this transaction ends, so a
        # concurrent request cannot delete it out from under the rewrite.
        cursor.execute(
            "SELECT operator_id FROM `operator` WHERE operator_id = %s FOR UPDATE",
            (operator_id,)
        )
        if cursor.fetchone() is None:
            connection.rollback()
            return not_found_response()

        cursor.execute(
            """
            UPDATE `operator`
               SET first_name          = %s,
                   last_name           = %s,
                   `role`              = %s,
                   certification_level = %s,
                   email               = %s
             WHERE operator_id = %s
            """,
            (
                cleaned["first_name"],
                cleaned["last_name"],
                cleaned["role"],
                cleaned["certification_level"],
                cleaned["email"],
                operator_id,
            )
        )

        # Replace, not merge: clear the old list, then write the new one.
        cursor.execute(
            "DELETE FROM operator_contact WHERE operator_id = %s",
            (operator_id,)
        )
        insert_contact_numbers(cursor, operator_id, cleaned["contact_numbers"])

        connection.commit()

        return jsonify({
            "success": True,
            "message": "Operator updated successfully",
            "data": build_operator_payload(operator_id, cleaned)
        }), 200

    except MySQLError as err:
        # Without this rollback the operator could keep its new details while
        # having lost its contact numbers.
        safe_rollback(connection)

        if err.errno == errorcode.ER_DUP_ENTRY:
            return duplicate_email_response()

        return db_failure(err, "update")

    finally:
        close_resources(cursor, connection)


